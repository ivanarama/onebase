package storage

import "time"

// FormatDisplayDate — дата для показа человеку: местное время, с секундами,
// если время суток не нулевое, иначе только дата. Так же выводит даты списков
// объектов (ui.fmtDateValue): период записи регистра — тот же момент, что и
// дата документа-регистратора, и 1С показывает его с точностью до секунды
// («12.08.2024 15:33:22»). Раньше период регистров выводился только датой,
// и движения одного дня было не отличить по времени.
func FormatDisplayDate(t time.Time) string {
	lt := t.In(time.Local)
	h, m, s := lt.Clock()
	if h == 0 && m == 0 && s == 0 {
		return lt.Format("02.01.2006")
	}
	return lt.Format("02.01.2006 15:04:05")
}
