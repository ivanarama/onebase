package storage

// Обслуживание файла/таблиц базы после массового удаления (план 114).
//
// Свёртка (`onebase rollup`) и сборка бинарников (`onebase gc-blobs --delete`)
// удаляют помногу, а место после удаления само не возвращается:
//
//   - SQLite отдаёт освободившиеся страницы в свой внутренний свободный список,
//     но файл не укорачивает — база на диске остаётся прежнего размера, пока
//     кто-нибудь не выполнит VACUUM;
//   - PostgreSQL пометит строки мёртвыми и уберёт их автовакуумом сам, но
//     статистика планировщика после удаления миллиона строк остаётся старой, и
//     запросы какое-то время строятся по несуществующему распределению.
//
// Отсюда разные операции для разных диалектов: SQLite надо сжимать, PostgreSQL
// — пересчитать статистику.

import (
	"context"
	"fmt"
)

// Reclaim приводит хранилище в порядок после массового удаления.
//
// SQLite: VACUUM — перезаписывает файл целиком, освобождая место. Берёт
// исключительную блокировку: на время операции с базой не работает никто, а на
// диске временно нужно место под вторую копию файла.
//
// PostgreSQL: VACUUM (ANALYZE) — без FULL. FULL переписывает таблицы под
// эксклюзивной блокировкой, и решать за администратора, что базу можно
// остановить, платформа не вправе; обычный VACUUM возвращает место внутри
// файлов и обновляет статистику, не мешая работе.
//
// Внутри транзакции не выполняется ни на одном диалекте — обе СУБД это
// запрещают, поэтому проверяем явно и говорим понятно.
func (db *DB) Reclaim(ctx context.Context) error {
	if HasTx(ctx) {
		return fmt.Errorf("обслуживание базы нельзя выполнять внутри транзакции")
	}
	if !db.IsSQLite() {
		if _, err := db.Exec(ctx, "VACUUM (ANALYZE)"); err != nil {
			return fmt.Errorf("обслуживание базы (VACUUM ANALYZE): %w", err)
		}
		return nil
	}
	if _, err := db.Exec(ctx, "VACUUM"); err != nil {
		return fmt.Errorf("обслуживание базы (VACUUM): %w", err)
	}
	// Одного VACUUM в режиме WAL мало: он перестраивает базу, но новое —
	// меньшее — содержимое уходит в журнал, а главный файл укорачивается лишь
	// на контрольной точке. Измерено: page_count падает с 1811 до 7, а размер
	// файла на диске остаётся прежним, пока не выполнен checkpoint.
	if _, err := db.Exec(ctx, "PRAGMA wal_checkpoint(TRUNCATE)"); err != nil {
		return fmt.Errorf("обслуживание базы (контрольная точка WAL): %w", err)
	}
	return nil
}

// ReclaimHint — короткое пояснение, что именно сделает Reclaim на этом
// диалекте. Нужно командам, которые предупреждают перед запуском.
func (db *DB) ReclaimHint() string {
	if db.IsSQLite() {
		return "VACUUM: файл базы будет перезаписан и уменьшится; " +
			"на время операции база заблокирована, а на диске нужно место под вторую копию файла"
	}
	return "VACUUM (ANALYZE): освободит место внутри файлов и обновит статистику планировщика; " +
		"работе не мешает (FULL не выполняется — он потребовал бы остановки базы)"
}
