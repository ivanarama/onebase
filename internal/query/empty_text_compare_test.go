// Незаполненный реквизит — ПУСТОЕ ЗНАЧЕНИЕ, а не «неизвестно»: запись без
// состояния должна попадать в отбор «состояние <> Завершено». В SQL
// NULL <> 'Завершено' даёт NULL, и такие записи молча выпадали из отчётов
// «что висит» — ровно те, ради которых отчёт и пишут.

func заявкаДляСравнений() []*metadata.Entity {
	return []*metadata.Entity{{
		Name: "Заявка", Kind: metadata.KindDocument,
		Fields: []metadata.Field{
			{Name: "Номер", Type: metadata.FieldTypeString},
			{Name: "Состояние", Type: metadata.FieldType("enum:СостояниеЗаявки"), EnumName: "СостояниеЗаявки"},
			{Name: "Комментарий", Type: metadata.FieldTypeString},
			{Name: "Количество", Type: metadata.FieldTypeNumber},
			{Name: "Дата", Type: metadata.FieldTypeDate},
		},
	}}
}

func скомпилировать(t *testing.T, текст string) string {
	t.Helper()
	res, err := Compile(текст, CompileOpts{Entities: заявкаДляСравнений()})
	if err != nil {
		t.Fatalf("компиляция %q: %v", текст, err)
	}
	return res.SQL
}

func TestСравнениеСПустым_ТекстовыеПоляОборачиваются(t *testing.T) {
	cases := []struct {
		имя   string
		текст string
	}{
		{"перечисление и <>", `ВЫБРАТЬ Номер ИЗ Документ.Заявка ГДЕ Состояние <> "Утверждена"`},
		{"перечисление и =", `ВЫБРАТЬ Номер ИЗ Документ.Заявка ГДЕ Состояние = ""`},
		{"строка", `ВЫБРАТЬ Номер ИЗ Документ.Заявка ГДЕ Комментарий <> "нет"`},
		{"константа слева", `ВЫБРАТЬ Номер ИЗ Документ.Заявка ГДЕ "Утверждена" <> Состояние`},
	}
	for _, c := range cases {
		t.Run(c.имя, func(t *testing.T) {
			sql := скомпилировать(t, c.текст)
			if !strings.Contains(sql, "COALESCE(") {
				t.Errorf("в SQL нет COALESCE — незаполненное значение выпадет из отбора:\n%s", sql)
			}
		})
	}
}

// Колонка, записанная через алиас источника, обязана получить ту же обёртку. В
// запросе с соединением алиас обязателен, и без этого один и тот же отбор,
// записанный двумя способами, возвращал разные наборы строк — к потере записей
// добавлялась зависимость результата от формы записи условия.
func TestСравнениеСПустым_КолонкаСАлиасомОборачиваетсяТакЖе(t *testing.T) {
	cases := []struct {
		имя   string
		текст string
		ждём  string
	}{
		{
			"колонка слева",
			`ВЫБРАТЬ Т.Номер ИЗ Документ.Заявка КАК Т ГДЕ Т.Состояние <> "Утверждена"`,
			"COALESCE(т.состояние, '') <> 'Утверждена'",
		},
		{
			"константа слева",
			`ВЫБРАТЬ Т.Номер ИЗ Документ.Заявка КАК Т ГДЕ "Утверждена" <> Т.Состояние`,
			"'Утверждена' <> COALESCE(т.состояние, '')",
		},
		{
			"сравнение с пустым",
			`ВЫБРАТЬ Т.Номер ИЗ Документ.Заявка КАК Т ГДЕ Т.Состояние = ""`,
			"COALESCE(т.состояние, '') = ''",
		},
	}
	for _, c := range cases {
		t.Run(c.имя, func(t *testing.T) {
			sql := скомпилировать(t, c.текст)
			if !strings.Contains(sql, c.ждём) {
				t.Errorf("ожидалось %q в SQL:\n%s", c.ждём, sql)
			}
		})
	}
}

func TestСравнениеСПустым_АлиасВСортировкеНеТрогаем(t *testing.T) {
	sql := скомпилировать(t,
		`ВЫБРАТЬ Т.Состояние ИЗ Документ.Заявка КАК Т УПОРЯДОЧИТЬ ПО Т.Состояние`)
	if strings.Contains(sql, "COALESCE(") {
		t.Errorf("вывод и сортировка не должны оборачиваться:\n%s", sql)
	}
}

// Условие соединения — не отбор: обёртка склеила бы там все незаполненные строки
// друг с другом (NULL с NULL не совпадает, пустая строка с пустой — совпадает).
// Неквалифицированная колонка в секции ИЗ и так уходит в SQL как есть, поэтому
// граница проведена по секции, а не по форме записи колонки.
func TestСравнениеСПустым_УсловиеСоединенияНеТрогаем(t *testing.T) {
	клиент := &metadata.Entity{
		Name: "КлиентСравнений", Kind: metadata.KindCatalog,
		Fields: []metadata.Field{{Name: "Состояние", Type: metadata.FieldTypeString}},
	}
	res, err := Compile(
		`ВЫБРАТЬ Т.Номер ИЗ Документ.Заявка КАК Т
		 ЛЕВОЕ СОЕДИНЕНИЕ Справочник.КлиентСравнений КАК К ПО Т.Состояние = К.Состояние
		 ГДЕ Т.Состояние <> "Утверждена"`,
		CompileOpts{Entities: append(заявкаДляСравнений(), клиент)})
	if err != nil {
		t.Fatalf("компиляция: %v", err)
	}
	on, where, найдено := strings.Cut(res.SQL, "WHERE")
	if !найдено {
		t.Fatalf("в SQL нет WHERE:\n%s", res.SQL)
	}
	if strings.Contains(on, "COALESCE(") {
		t.Errorf("условие соединения не должно оборачиваться:\n%s", res.SQL)
	}
	if !strings.Contains(where, "COALESCE(т.состояние, '')") {
		t.Errorf("отбор в WHERE обязан оборачиваться:\n%s", res.SQL)
	}
}

func TestСравнениеСПустым_ЧислаИДатыНеТрогаем(t *testing.T) {
	// У числа пустое значение — 0, и текущее поведение (NULL не попадает в
	// «<> 0») уже совпадает с прикладным смыслом; COALESCE там только помешал бы
	// индексу. Дата — по той же причине.
	for _, текст := range []string{
		`ВЫБРАТЬ Номер ИЗ Документ.Заявка ГДЕ Количество <> 0`,
		`ВЫБРАТЬ Номер ИЗ Документ.Заявка ГДЕ Дата = &Д`,
	} {
		sql := скомпилировать(t, текст)
		if strings.Contains(sql, "COALESCE(") {
			t.Errorf("%q: COALESCE не должен появляться:\n%s", текст, sql)
		}
	}
}

func TestСравнениеСПустым_ВыводИСортировкаНеТрогаются(t *testing.T) {
	// Колонка в списке выборки, в ГРУППИРОВАТЬ и в УПОРЯДОЧИТЬ остаётся собой:
	// NULL в выводе не должен подменяться пустой строкой.
	sql := скомпилировать(t,
		`ВЫБРАТЬ Состояние КАК С, КОЛИЧЕСТВО(*) КАК К ИЗ Документ.Заявка
		 СГРУППИРОВАТЬ ПО Состояние УПОРЯДОЧИТЬ ПО Состояние`)
	if strings.Contains(sql, "COALESCE(") {
		t.Errorf("вывод/группировка/сортировка не должны оборачиваться:\n%s", sql)
	}
}
