// меткиЗапроса компилирует текст запроса под диалект базы, исполняет его и
// возвращает первую колонку результата строками.
func меткиЗапроса(t *testing.T, ctx context.Context, db *storage.DB, ents []*metadata.Entity, текст string) []string {
	t.Helper()
	res, err := query.Compile(текст, query.CompileOpts{Dialect: db.Dialect(), Entities: ents})
	if err != nil {
		t.Fatalf("компиляция %q: %v", текст, err)
	}
	rows, cols, err := db.RunQuery(ctx, res.SQL, res.Args)
	if err != nil {
		t.Fatalf("выполнение %s: %v", res.SQL, err)
	}
	var out []string
	for _, r := range rows {
		// Имя колонки результата — как его вернул SQL (метка), а не как
		// написано в тексте запроса.
		out = append(out, fmt.Sprint(r[cols[0]]))
	}
	return out
}

func сверитьМетки(t *testing.T, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("получено %v, ожидалось %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("получено %v, ожидалось %v", got, want)
		}
	}
}

// Сквозная проверка на реальных данных: запись с НЕЗАПОЛНЕННЫМ состоянием
// должна попадать в отбор «состояние <> Завершено». Это ровно та запись, ради
// которой пишут отчёт «что висит», — а в SQL NULL <> 'Завершено' даёт NULL, и
// раньше она молча выпадала.
//
// Тест матричный, потому что правило меняет исполняемый SQL: колонка уезжает в
// COALESCE, а типизация COALESCE на PostgreSQL строгая. Проверка одного диалекта
// показала бы зелёное, а расхождение вылезло бы в рантайме прикладного отчёта.
func TestНезаполненноеСостояниеПопадаетВОтбор(t *testing.T) {
	dbtest.ForEachDialect(t, func(t *testing.T, db *storage.DB) {
		ctx := context.Background()
		обращение := &metadata.Entity{
			Name: "ОбращениеПустое", Kind: metadata.KindDocument,
			Fields: []metadata.Field{
				{Name: "Метка", Type: metadata.FieldTypeString},
				{Name: "СостояниеОбращения", Type: metadata.FieldType("enum:СостояниеОбращения"), EnumName: "СостояниеОбращения"},
				{Name: "КоличествоИтогов", Type: metadata.FieldTypeNumber},
			},
		}
		if err := db.Migrate(ctx, []*metadata.Entity{обращение}); err != nil {
			t.Fatalf("миграция: %v", err)
		}
		for _, поля := range []map[string]any{
			{"Метка": "ОБР-001", "СостояниеОбращения": "Открыто", "КоличествоИтогов": 1},
			{"Метка": "ОБР-002", "СостояниеОбращения": "Завершено", "КоличествоИтогов": 2},
			// Создана мимо модуля: состояние и число не заполнены — в БД NULL.
			{"Метка": "ОБР-003"},
		} {
			if err := db.Upsert(ctx, обращение.Name, uuid.New(), поля, обращение); err != nil {
				t.Fatalf("запись %v: %v", поля["Метка"], err)
			}
		}

		метки := func(t *testing.T, текст string) []string {
			t.Helper()
			return меткиЗапроса(t, ctx, db, []*metadata.Entity{обращение}, текст)
		}
		сверить := сверитьМетки

		t.Run("незавершённые включают запись без состояния", func(t *testing.T) {
			сверить(t, метки(t, `ВЫБРАТЬ Метка ИЗ Документ.ОбращениеПустое
				ГДЕ СостояниеОбращения <> "Завершено" УПОРЯДОЧИТЬ ПО Метка`),
				[]string{"ОБР-001", "ОБР-003"})
		})

		// Тот же отбор, записанный через алиас источника. В запросе с соединением
		// алиас обязателен, поэтому запись без него и с ним обязаны отдавать один
		// набор строк: расхождение здесь хуже исходного дефекта — к потере записей
		// добавилась бы зависимость результата от формы записи условия.
		t.Run("через алиас источника отбор тот же", func(t *testing.T) {
			сверить(t, метки(t, `ВЫБРАТЬ Т.Метка ИЗ Документ.ОбращениеПустое КАК Т
				ГДЕ Т.СостояниеОбращения <> "Завершено" УПОРЯДОЧИТЬ ПО Т.Метка`),
				[]string{"ОБР-001", "ОБР-003"})
		})

		t.Run("отбор по пустому состоянию находит запись", func(t *testing.T) {
			сверить(t, метки(t, `ВЫБРАТЬ Метка ИЗ Документ.ОбращениеПустое ГДЕ СостояниеОбращения = ""`),
				[]string{"ОБР-003"})
			сверить(t, метки(t, `ВЫБРАТЬ Т.Метка ИЗ Документ.ОбращениеПустое КАК Т ГДЕ Т.СостояниеОбращения = ""`),
				[]string{"ОБР-003"})
		})

		t.Run("незаполненное число по-прежнему не равно нулю в отборе", func(t *testing.T) {
			// У числа пустое значение — 0, и «<> 0» для NULL не срабатывает: это
			// совпадает с прикладным смыслом и намеренно оставлено как было.
			сверить(t, метки(t, `ВЫБРАТЬ Метка ИЗ Документ.ОбращениеПустое
				ГДЕ КоличествоИтогов <> 0 УПОРЯДОЧИТЬ ПО Метка`),
				[]string{"ОБР-001", "ОБР-002"})
		})
	})
}

// Правило действует только на поля ОСНОВНОГО источника, и проверка этого —
// матричная, потому что расхождение диалектов здесь не косметическое.
//
// Тип колонки компилятор берёт по ИМЕНИ поля из карты основного источника. При
// одноимённых полях разного типа (`Заявка.Код` строка, `Клиент.Код` число) отбор
// `ГДЕ К.Код <> 0` получал обёртку строкового поля по чужому типу. На SQLite это
// безвредно — number там хранится как TEXT. На PostgreSQL number это NUMERIC,
// нетипизированный литерал пустой строки приводится к нему, и запрос падает на
// этапе плана независимо от числа строк: работавший до правила отбор переставал
// работать совсем. Одного диалекта тут мало ровно поэтому.
// Бухгалтерский регистр тоже должен применить правило пустого текста к своим
// строковым полям основного источника, включая SubcontoN.
func TestБухгалтерскийРегистрПустойТекстВОстатках(t *testing.T) {
	dbtest.ForEachDialect(t, func(t *testing.T, db *storage.DB) {
		ctx := context.Background()
		ar := &metadata.AccountRegister{
			Name:      "ОстаткиПустоСубконто",
			Accounts:  "Основной",
			Resources: []metadata.Field{{Name: "Сумма", Type: metadata.FieldTypeNumber}},
			Subconto:  []metadata.Field{{Name: "Номенклатура", Type: metadata.FieldTypeString}},
		}
		if err := db.MigrateAccountRegisters(ctx, []*metadata.AccountRegister{ar}); err != nil {
			t.Fatalf("миграция: %v", err)
		}
		if err := db.EnsureAccountsTable(ctx); err != nil {
			t.Fatalf("синхронизация справочника счетов: %v", err)
		}
		if err := db.SyncAccounts(ctx, []*metadata.ChartOfAccounts{{
			Name: "Основной",
			Accounts: []metadata.Account{
				{Code: "41", Kind: "active"},
				{Code: "60", Kind: "passive"},
			},
		}}); err != nil {
			t.Fatalf("перенос счетов: %v", err)
		}
		if err := db.WriteAccountMovements(ctx, ar.Name, "Док", uuid.New(), []map[string]any{
			{"счётдт": "60", "счёткт": "41", "сумма": float64(5)},
			{"счётдт": "60", "счёткт": "60", "субконто1": "Контрагент", "сумма": float64(7)},
		}, ar, nil); err != nil {
			t.Fatalf("запись движений: %v", err)
		}

		run := func(t *testing.T, текст string) []string {
			t.Helper()
			res, err := query.Compile(текст, query.CompileOpts{
				Dialect:     db.Dialect(),
				AccountRegs: []*metadata.AccountRegister{ar},
			})
			if err != nil {
				t.Fatalf("компиляция %q: %v", текст, err)
			}
			rows, cols, err := db.RunQuery(ctx, res.SQL, res.Args)
			if err != nil {
				t.Fatalf("выполнение %s: %v", res.SQL, err)
			}
			var out []string
			for _, r := range rows {
				out = append(out, fmt.Sprint(r[cols[0]]))
			}
			return out
		}

		сверитьМетки(t, run(t, `ВЫБРАТЬ Счет ИЗ РегистрБухгалтерии.ОстаткиПустоСубконто.Остатки()
			ГДЕ Счет = "41" И Субконто1 <> "Завершено"`), []string{"41"})
	})
}

func TestОдноимённыеПоляРазногоТипаНеЛомаютОтбор(t *testing.T) {
	dbtest.ForEachDialect(t, func(t *testing.T, db *storage.DB) {
		ctx := context.Background()
		заявка := &metadata.Entity{
			Name: "ЗаявкаКод", Kind: metadata.KindDocument,
			Fields: []metadata.Field{
				{Name: "Метка", Type: metadata.FieldTypeString},
				{Name: "Код", Type: metadata.FieldTypeString}, // строка
				{Name: "Клиент", Type: metadata.FieldTypeString},
			},
		}
		клиент := &metadata.Entity{
			Name: "КлиентКод", Kind: metadata.KindCatalog,
			Fields: []metadata.Field{
				{Name: "Имя", Type: metadata.FieldTypeString},
				{Name: "Код", Type: metadata.FieldTypeNumber}, // то же имя, другой тип
			},
		}
		ents := []*metadata.Entity{заявка, клиент}
		if err := db.Migrate(ctx, ents); err != nil {
			t.Fatalf("миграция: %v", err)
		}
		for _, поля := range []map[string]any{
			{"Метка": "З-1", "Код": "А-1", "Клиент": "К-1"},
			{"Метка": "З-2", "Код": "А-2", "Клиент": "К-2"},
			// Создана мимо модуля: ни кода, ни клиента — в БД NULL.
			{"Метка": "З-3"},
		} {
			if err := db.Upsert(ctx, заявка.Name, uuid.New(), поля, заявка); err != nil {
				t.Fatalf("запись %v: %v", поля["Метка"], err)
			}
		}
		for _, поля := range []map[string]any{
			{"Имя": "К-1", "Код": 10},
			{"Имя": "К-2", "Код": 20},
		} {
			if err := db.Upsert(ctx, клиент.Name, uuid.New(), поля, клиент); err != nil {
				t.Fatalf("запись %v: %v", поля["Имя"], err)
			}
		}

		соединение := `ИЗ Документ.ЗаявкаКод КАК Т
			ЛЕВОЕ СОЕДИНЕНИЕ Справочник.КлиентКод КАК К ПО Т.Клиент = К.Имя `
		метки := func(t *testing.T, текст string) []string {
			t.Helper()
			return меткиЗапроса(t, ctx, db, ents, текст)
		}

		t.Run("числовое поле присоединённой таблицы сравнивается как число", func(t *testing.T) {
			сверитьМетки(t, метки(t, `ВЫБРАТЬ Т.Метка `+соединение+
				`ГДЕ К.Код <> 0 УПОРЯДОЧИТЬ ПО Т.Метка`),
				[]string{"З-1", "З-2"})
		})

		// Обратная сторона границы: сужение правила не должно съесть саму
		// исправляемую возможность — в запросе С СОЕДИНЕНИЕМ отбор по полю
		// основного источника обязан по-прежнему находить незаполненные.
		t.Run("поле основного источника в том же запросе находит незаполненное", func(t *testing.T) {
			сверитьМетки(t, метки(t, `ВЫБРАТЬ Т.Метка `+соединение+
				`ГДЕ Т.Код <> "А-1" УПОРЯДОЧИТЬ ПО Т.Метка`),
				[]string{"З-2", "З-3"})
		})
	})
}

// Условие соединения обёртку не получает — иначе незаполненное поле слева
// совпало бы с незаполненным справа (NULL с NULL не совпадает, пустая строка с
// пустой — совпадает) и соединение склеило бы строки декартовым произведением.
//
// Проверка на данных, а не на тексте SQL: цена ошибки здесь — лишние строки в
// отчёте, и именно её надо удержать. Формы запроса отличаются одним ГДЕ внутри
// подзапроса в ИЗ: секция запроса ведётся не одним бегущим полем, а отдельно
// для каждого SELECT, иначе ГДЕ подзапроса переводил под обёртку все
// последующие ПО — и обычные соединения тоже, до конца запроса.
func TestУсловиеСоединенияНеСклеиваетНезаполненные(t *testing.T) {
	dbtest.ForEachDialect(t, func(t *testing.T, db *storage.DB) {
		ctx := context.Background()
		обращение := &metadata.Entity{
			Name: "ОбращениеСоединения", Kind: metadata.KindDocument,
			Fields: []metadata.Field{
				{Name: "Метка", Type: metadata.FieldTypeString},
				{Name: "Состояние", Type: metadata.FieldTypeString},
			},
		}
		клиент := &metadata.Entity{
			Name: "КлиентСоединения", Kind: metadata.KindCatalog,
			Fields: []metadata.Field{
				{Name: "Имя", Type: metadata.FieldTypeString},
				{Name: "Состояние", Type: metadata.FieldTypeString},
			},
		}
		ents := []*metadata.Entity{обращение, клиент}
		if err := db.Migrate(ctx, ents); err != nil {
			t.Fatalf("миграция: %v", err)
		}
		// По две записи с незаполненным состоянием с каждой стороны: если обёртка
		// попадёт в ПО, две строки слева превратятся в четыре.
		for _, поля := range []map[string]any{{"Метка": "ОБР-101"}, {"Метка": "ОБР-102"}} {
			if err := db.Upsert(ctx, обращение.Name, uuid.New(), поля, обращение); err != nil {
				t.Fatalf("запись %v: %v", поля["Метка"], err)
			}
		}
		for _, поля := range []map[string]any{{"Имя": "К-1"}, {"Имя": "К-2"}} {
			if err := db.Upsert(ctx, клиент.Name, uuid.New(), поля, клиент); err != nil {
				t.Fatalf("запись %v: %v", поля["Имя"], err)
			}
		}

		t.Run("обычное соединение", func(t *testing.T) {
			сверитьМетки(t, меткиЗапроса(t, ctx, db, ents,
				`ВЫБРАТЬ Т.Метка ИЗ Документ.ОбращениеСоединения КАК Т
				 ЛЕВОЕ СОЕДИНЕНИЕ Справочник.КлиентСоединения КАК К ПО Т.Состояние = К.Состояние
				 УПОРЯДОЧИТЬ ПО Т.Метка`),
				[]string{"ОБР-101", "ОБР-102"})
		})

		// Тот же запрос, но источник соединения — подзапрос со своим ГДЕ. Отбор
		// внутри подзапроса не должен ничего менять снаружи.
		t.Run("источник соединения — подзапрос с ГДЕ", func(t *testing.T) {
			сверитьМетки(t, меткиЗапроса(t, ctx, db, ents,
				`ВЫБРАТЬ Т.Метка ИЗ Документ.ОбращениеСоединения КАК Т
				 ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ Состояние ИЗ Справочник.КлиентСоединения ГДЕ Имя <> "нет") КАК К
				   ПО Т.Состояние = К.Состояние
				 УПОРЯДОЧИТЬ ПО Т.Метка`),
				[]string{"ОБР-101", "ОБР-102"})
		})

		// Заражалось не только соединение с подзапросом: под обёртку уезжали и все
		// следующие за ним обычные ПО, до конца запроса.
		t.Run("обычное соединение после подзапроса с ГДЕ", func(t *testing.T) {
			сверитьМетки(t, меткиЗапроса(t, ctx, db, ents,
				`ВЫБРАТЬ Т.Метка ИЗ Документ.ОбращениеСоединения КАК Т
				 ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ Состояние ИЗ Справочник.КлиентСоединения ГДЕ Имя <> "нет") КАК К
				   ПО Т.Состояние = К.Состояние
				 ЛЕВОЕ СОЕДИНЕНИЕ Справочник.КлиентСоединения КАК К2 ПО Т.Состояние = К2.Состояние
				 УПОРЯДОЧИТЬ ПО Т.Метка`),
				[]string{"ОБР-101", "ОБР-102"})
		})

		// То же соединение, записанное запятой. Границу «секцию ИЗ не трогаем»
		// эта форма обходит: условие стоит в ГДЕ, а не в ПО. Склейку снимает
		// вторая граница — правая сторона принадлежит присоединённому источнику,
		// обёртки не получает, и «незаполненное = незаполненное» остаётся ложью.
		t.Run("соединение запятой не склеивает незаполненные", func(t *testing.T) {
			сверитьМетки(t, меткиЗапроса(t, ctx, db, ents,
				`ВЫБРАТЬ Т.Метка ИЗ Документ.ОбращениеСоединения КАК Т, Справочник.КлиентСоединения КАК К
				 ГДЕ Т.Состояние = К.Состояние
				 УПОРЯДОЧИТЬ ПО Т.Метка`),
				nil)
		})

		// Обратная сторона границы: внешний отбор после подзапроса обёртку
		// получать обязан — иначе починка съела бы саму исправляемую возможность.
		t.Run("внешний отбор после подзапроса оборачивается", func(t *testing.T) {
			сверитьМетки(t, меткиЗапроса(t, ctx, db, ents,
				`ВЫБРАТЬ Т.Метка ИЗ Документ.ОбращениеСоединения КАК Т
				 ЛЕВОЕ СОЕДИНЕНИЕ (ВЫБРАТЬ Состояние ИЗ Справочник.КлиентСоединения ГДЕ Имя <> "нет") КАК К
				   ПО Т.Состояние = К.Состояние
				 ГДЕ Т.Состояние <> "Завершено"
				 УПОРЯДОЧИТЬ ПО Т.Метка`),
				[]string{"ОБР-101", "ОБР-102"})
		})
	})
}
