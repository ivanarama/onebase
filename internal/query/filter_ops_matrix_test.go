package query_test

import (
	"context"
	"fmt"
	"testing"

	"github.com/google/uuid"

	"github.com/ivantit66/onebase/internal/dbtest"
	"github.com/ivantit66/onebase/internal/metadata"
	"github.com/ivantit66/onebase/internal/query"
	"github.com/ivantit66/onebase/internal/storage"
)

// Дефект #1542: конструктор отбора предлагает «НЕ ЕСТЬ ПУСТО» и «ПОДОБНО»,
// но оба давали невалидный SQL: «NOT IS NULL» не парсит ни одна СУБД, а
// «ПОДОБНО» вообще не было в таблице ключевых слов и уходило в SQL как есть.
//
// Тест матричный: обе конструкции меняют исполняемый SQL, и расхождение
// диалектов здесь — ровно то, что матрица обязана ловить.
func TestОтрицаниеПустотыИПодобноНаОбоихДиалектах(t *testing.T) {
	dbtest.ForEachDialect(t, func(t *testing.T, db *storage.DB) {
		ctx := context.Background()
		заявка := &metadata.Entity{
			Name: "ОтборПустоты", Kind: metadata.KindDocument,
			Fields: []metadata.Field{
				{Name: "Метка", Type: metadata.FieldTypeString},
				{Name: "Наименование", Type: metadata.FieldTypeString},
				{Name: "Подобно", Type: metadata.FieldTypeString}, // имя поля = имя оператора
			},
		}
		if err := db.Migrate(ctx, []*metadata.Entity{заявка}); err != nil {
			t.Fatalf("миграция: %v", err)
		}
		for _, поля := range []map[string]any{
			{"Метка": "З-1", "Наименование": "Зубр", "Подобно": "абв"},
			{"Метка": "З-2", "Наименование": "Пила", "Подобно": "абв"},
			// Создана мимо модуля: всё не заполнено — в БД NULL.
			{"Метка": "З-3"},
		} {
			if err := db.Upsert(ctx, заявка.Name, uuid.New(), поля, заявка); err != nil {
				t.Fatalf("запись %v: %v", поля["Метка"], err)
			}
		}

		прогнать := func(t *testing.T, текст string, параметры map[string]any) []string {
			t.Helper()
			opts := query.CompileOpts{Dialect: db.Dialect(), Entities: []*metadata.Entity{заявка}}
			if параметры != nil {
				opts.Params = параметры
			}
			res, err := query.Compile(текст, opts)
			if err != nil {
				t.Fatalf("компиляция %q: %v", текст, err)
			}
			rows, cols, err := db.RunQuery(ctx, res.SQL, res.Args)
			if err != nil {
				t.Fatalf("выполнение %s: %v", res.SQL, err)
			}
			var out []string
			for _, r := range rows {
				out = append(out, fmt.Sprint(r[cols[0]]))
			}
			return out
		}

		t.Run("НЕ ЕСТЬ ПУСТО исключает незаполненные", func(t *testing.T) {
			// Ровно форма из конструктора отбора: раньше это компилировалось
			// в «NOT IS NULL» и падало при исполнении.
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Наименование НЕ ЕСТЬ ПУСТО УПОРЯДОЧИТЬ ПО Метка`, nil),
				[]string{"З-1", "З-2"})
		})

		t.Run("ЕСТЬ НЕ ПУСТО — тот же набор", func(t *testing.T) {
			// Работавший раньше порядок слов обязан пережить соседнюю правку.
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Наименование ЕСТЬ НЕ ПУСТО УПОРЯДОЧИТЬ ПО Метка`, nil),
				[]string{"З-1", "З-2"})
		})

		t.Run("ЕСТЬ ПУСТО находит незаполненное", func(t *testing.T) {
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Наименование ЕСТЬ ПУСТО`, nil),
				[]string{"З-3"})
		})

		t.Run("регистр ключевых слов не важен", func(t *testing.T) {
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Наименование не есть пусто УПОРЯДОЧИТЬ ПО Метка`, nil),
				[]string{"З-1", "З-2"})
		})

		t.Run("ПОДОБНО с процентом и подчёркиванием", func(t *testing.T) {
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Наименование ПОДОБНО "З%"`, nil),
				[]string{"З-1"})
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Наименование ПОДОБНО "_ила"`, nil),
				[]string{"З-2"})
		})

		t.Run("ПОДОБНО с параметром", func(t *testing.T) {
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Наименование ПОДОБНО &Шаблон`,
				map[string]any{"Шаблон": "З%"}),
				[]string{"З-1"})
		})

		t.Run("ПОДОБНО у квалифицированного поля", func(t *testing.T) {
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Т.Метка ИЗ Документ.ОтборПустоты КАК Т
				ГДЕ Т.Наименование ПОДОБНО "П%" УПОРЯДОЧИТЬ ПО Т.Метка`, nil),
				[]string{"З-2"})
		})

		t.Run("поле Подобно работает и рядом с оператором ПОДОБНО", func(t *testing.T) {
			// Имя не резервируется: в позиции операнда это поле, в позиции
			// оператора — LIKE. В одном условии обе роли рядом.
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Подобно ПОДОБНО "а%" УПОРЯДОЧИТЬ ПО Метка`, nil),
				[]string{"З-1", "З-2"})
			сверитьМетки(t, прогнать(t, `ВЫБРАТЬ Метка ИЗ Документ.ОтборПустоты
				ГДЕ Подобно = "абв" И Подобно ПОДОБНО "%б%" УПОРЯДОЧИТЬ ПО Метка`, nil),
				[]string{"З-1", "З-2"})
		})
	})
}
