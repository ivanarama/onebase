'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const test = require('node:test');
const vm = require('node:vm');

const source = fs.readFileSync('static/ui.js', 'utf8');
const start = source.indexOf('function obInitFormDirty()');
const end = source.indexOf('obReady(obInitFormDirty);', start);
assert.ok(start >= 0 && end > start, 'auto-form dirty slice not found');
const dirtyCode = source.slice(start, end);
const cancelStart = source.indexOf('function obSendPopupCancel()');
const cancelEnd = source.indexOf('function obInitFormDelegates()', cancelStart);
assert.ok(cancelStart >= 0 && cancelEnd > cancelStart, 'popup cancel slice not found');
const cancelCode = source.slice(cancelStart, cancelEnd);
const imageStart = source.indexOf('function obImageClear(btn)');
const imageEnd = source.indexOf('function obSplitDataList', imageStart);
assert.ok(imageStart >= 0 && imageEnd > imageStart, 'image clear slice not found');
const imageCode = source.slice(imageStart, imageEnd);

function runtime() {
  const handlers = new Map();
  const shell = [];
  const form = {
    addEventListener(type, fn) { handlers.set(type, fn); }
  };
  const document = {
    title: 'Form',
    querySelector(selector) { return selector === '#main-form[data-ob-dirty-watch="1"]' ? form : null; },
    addEventListener() {},
    getElementById() { return null; }
  };
  const context = {
    Promise,
    document,
    confirm() { return true; },
    obHasBlockingModal() { return false; },
    obUIMessage(name, fallback) { return fallback; },
    addEventListener() {},
    obSetEmbeddedDirty(value) { shell.push(!!value); }
  };
  context.window = context;
  vm.runInNewContext(dirtyCode + '\nobInitFormDirty();', context, {filename: 'auto-form-dirty.js'});
  return {context, handlers, shell};
}

test('autogenerated submit clears local and shell dirty only after a non-cancelled dispatch', async () => {
  const app = runtime();
  app.handlers.get('input')({target: {}});
  assert.equal(app.context._obFormDirty, true);

  const cancelled = {defaultPrevented: false};
  app.handlers.get('submit')(cancelled);
  cancelled.defaultPrevented = true;
  await Promise.resolve();
  assert.equal(app.context._obFormDirty, true);
  assert.deepEqual(app.shell, [true]);

  const accepted = {defaultPrevented: false};
  app.handlers.get('submit')(accepted);
  await Promise.resolve();
  assert.equal(app.context._obFormDirty, false);
  assert.deepEqual(app.shell, [true, false]);
});

test('autogenerated popup cancel asks before posting a destructive close', () => {
  const posted = [];
	const dirty = [];
  let allow = false;
  const context = {
    _obFormDirty: true,
    confirm() { return allow; },
    obUIMessage(name, fallback) { return fallback; },
	  obSetAutoFormDirty(value) { this._obFormDirty = !!value; dirty.push(!!value); },
    parent: {postMessage(message) { posted.push(message); }}
  };
  context.window = context;
  vm.runInNewContext(cancelCode, context, {filename: 'auto-popup-cancel.js'});
  assert.equal(context.obSendPopupCancel(), false);
  assert.equal(posted.length, 0);
	assert.equal(context._obFormDirty, true);
	assert.deepEqual(dirty, []);
  allow = true;
  assert.equal(context.obSendPopupCancel(), true);
  assert.equal(posted.length, 1);
  assert.equal(posted[0].source, 'obRefCancel');
	assert.equal(context._obFormDirty, false);
	assert.deepEqual(dirty, [false]);
});

test('programmatic image clear marks managed or autogenerated form dirty', () => {
  for (const setter of ['obSetManagedFormDirty', 'obSetAutoFormDirty']) {
    const reports = [];
    const hidden = {value: 'image-ref'};
    const preview = {style: {}, querySelector() { return {removeAttribute() {}}; }};
    const wrap = {querySelector(selector) { return selector === 'input[type=hidden]' ? hidden : preview; }};
    const btn = {style: {}, closest() { return wrap; }};
    const context = {[setter](value) { reports.push(value); }};
    context.window = context;
    vm.runInNewContext(imageCode, context, {filename: 'image-clear.js'});
    context.obImageClear(btn);
    assert.equal(hidden.value, '');
    assert.deepEqual(reports, [true]);
  }
});
