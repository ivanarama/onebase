package ui

import (
	"testing"
	"time"
)

// Ожидания по датам переписаны в #1076 ОСОЗНАННО, а не подогнаны под новый код.
//
// Раньше здесь стояло time.Date(..., time.UTC) с ожиданием того же настенного
// времени — то есть тест утверждал, что момент печатается в зоне, в которой его
// отдали. Для отчёта это неверно: человек в зоне +03:00, глядя на метку 13:05
// UTC, должен видеть 16:05, а не 13:05. Прежнее ожидание кодифицировало дефект,
// из-за которого на SQLite (драйвер всегда отдаёт UTC) в отчётах и панели
// деталей съезжал ещё и календарный день.
//
// Чтобы тест не зависел от зоны машины, входные значения задаются в time.Local,
// а отдельный случай явно проверяет ПЕРЕСЧЁТ зоны.
func TestFmtReportCell(t *testing.T) {
	// Зона фиксируется на время теста: без этого «пересчёт зоны» на UTC-раннере
	// не проверял бы ничего, а с LoadLocation тест зависел бы от наличия tzdata.
	saved := time.Local
	time.Local = time.FixedZone("MSK", 3*60*60)
	t.Cleanup(func() { time.Local = saved })

	cases := []struct {
		name string
		in   any
		want string
	}{
		{"nil → пусто", nil, ""},
		{"дата без времени", time.Date(2026, 5, 22, 0, 0, 0, 0, time.Local), "22.05.2026"},
		{"дата со временем", time.Date(2026, 5, 22, 13, 5, 9, 0, time.Local), "22.05.2026 13:05:09"},
		// Момент в UTC показывается в МЕСТНОЙ зоне. Это и есть суть #1076:
		// драйверы отдают дату в разных зонах, а пользователь должен видеть свою.
		{"момент в UTC пересчитывается в местную зону",
			time.Date(2026, 5, 22, 13, 5, 9, 0, time.UTC), "22.05.2026 16:05:09"},
		// Тот же пересчёт может сдвинуть КАЛЕНДАРНЫЙ ДЕНЬ — именно так на SQLite
		// дата 22.05 показывалась как 21.05.
		{"пересчёт зоны сдвигает календарный день",
			time.Date(2026, 5, 21, 22, 0, 0, 0, time.UTC), "22.05.2026 01:00:00"},
		{"булево истина → галочка", true, "✓"},
		{"булево ложь → прочерк", false, "—"},
		{"целое float64 → разделители", float64(1234567), "1 234 567"},
		{"дробное float64", float64(1234.5), "1234.50"},
		{"int", 1000000, "1 000 000"},
		{"int64", int64(2500), "2 500"},
		{"строка-дата ISO", "2026-05-22", "22.05.2026"},
		{"строка-дата с временем", "2026-05-22 13:05:09", "22.05.2026 13:05:09"},
		{"строка-дата с зоной пересчитывается", "2026-05-22T13:05:09Z", "22.05.2026 16:05:09"},
		{"обычная строка", "Тумбочка", "Тумбочка"},
		{"короткая строка не парсится как дата", "ООО", "ООО"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := fmtReportCell(c.in); got != c.want {
				t.Errorf("fmtReportCell(%v) = %q, want %q", c.in, got, c.want)
			}
		})
	}
}

// Числовое булево из SQLite отсюда неотличимо от числа — и это не недосмотр, а
// граница: int64(1) может быть и единицей, и «истиной». Разбирать его обязан
// тот, у кого есть тип поля (fieldDisplayText). Тест фиксирует границу, чтобы
// следующий читатель не «починил» её, сломав показ чисел.
func TestFmtReportCell_ЧисловоеБулевоБезТипаОстаётсяЧислом(t *testing.T) {
	if got := fmtReportCell(int64(1)); got != "1" {
		t.Errorf("fmtReportCell(int64(1)) = %q, ожидалось %q", got, "1")
	}
}
