// Package fsmode держит права, с которыми OneBase создаёт файлы и каталоги.
package fsmode

import "io/fs"

// Права на файлы и каталоги — одно решение на весь репозиторий.
//
// Почему File/Dir открыты для чтения группе и остальным, а не 0600/0750:
// конфигурацию, выгрузки и отчёты пишет один процесс, а читает другой, и это
// МОГУТ БЫТЬ РАЗНЫЕ ПОЛЬЗОВАТЕЛИ. `onebase service install --user <имя>`
// генерирует systemd-юнит с произвольным User; типичная установка — админ
// раскладывает конфигурацию из лаунчера под своей учёткой, а сервис работает
// под onebase. При 0600 сервис перестаёт читать конфигурацию, причём молча и
// не сразу.
//
// Secret* — для того, что читает ТОЛЬКО владелец: реестр баз со строкой
// подключения (пароль от БД), журналы, диагностические следы. Там ослаблять
// нечего, и они закрыты.
//
// Держать эти значения константами, а не литералами по коду, нужно ровно
// затем, чтобы решение было видно и его можно было пересмотреть в одном месте.
const (
	// File — файлы, которые может читать сервис под другим пользователем.
	File fs.FileMode = 0o644
	// Dir — каталоги под такими файлами.
	Dir fs.FileMode = 0o755
	// SecretFile — файлы только для владельца.
	SecretFile fs.FileMode = 0o600
	// SecretDir — каталоги только для владельца.
	SecretDir fs.FileMode = 0o700
)
