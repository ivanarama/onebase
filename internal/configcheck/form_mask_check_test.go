package configcheck

import (
	"strings"
	"testing"
)

// `mask` рендерится в HTML-атрибут pattern, то есть это регулярное выражение.
// Шаблон в стиле 1С «00.00.00» отвергает 12.34.56 и принимает 00X00Y00 — маска
// не пропускает ровно тот формат, ради которого написана (#763).
func TestMaskDiagnosis(t *testing.T) {
	cases := []struct {
		name, mask string
		warn       bool
		contains   string
	}{
		{"шаблон 1С с точками", "00.00.00", true, "любой символ"},
		// Телефонный шаблон 1С вообще не компилируется как regexp: ведущий «+»
		// для регулярного выражения — оператор повтора без аргумента. Отдельная
		// ветка предупреждения, и она даже точнее.
		{"телефонный шаблон 1С", "+7(000)000-00-00", true, "не компилируется"},
		{"телефонный шаблон без плюса", "7(000)000-00-00", true, "любой символ"},
		{"шаблон из девяток", "99/99/9999", true, "любой символ"},
		{"настоящий regexp", `\d{2}\.\d{2}\.\d{2}`, false, ""},
		{"regexp с классом", `[А-Я]{2}-\d+`, false, ""},
		{"сломанный regexp", `\d{2}\.(`, true, "не компилируется"},
		{"пусто", "", false, ""},
		// Одиночные литералы без заполнителей — не наш случай: это осмысленное
		// выражение «строка равна XX», и ругаться на него не за что.
		{"литерал без заполнителей", "abc", false, ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			msg, fix := maskDiagnosis(c.mask)
			if c.warn && msg == "" {
				t.Fatalf("маска %q принята молча", c.mask)
			}
			if !c.warn && msg != "" {
				t.Fatalf("маска %q помечена зря: %s", c.mask, msg)
			}
			if c.warn {
				if !strings.Contains(msg, c.contains) {
					t.Errorf("текст не объясняет причину (%q): %s", c.contains, msg)
				}
				if fix == "" {
					t.Error("нет подсказки, как записать правильно")
				}
			}
		})
	}
}

// Подсказка обязана называть рабочий вариант: без него предупреждение только
// сообщает о проблеме, но не помогает.
func TestMaskDiagnosis_ПодсказкаСодержитРабочийПример(t *testing.T) {
	_, fix := maskDiagnosis("00.00.00")
	if !strings.Contains(fix, `\d{2}\.\d{2}\.\d{2}`) {
		t.Fatalf("подсказка не показывает рабочее выражение: %s", fix)
	}
}
