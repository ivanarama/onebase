func runAIGuide(cmd *cobra.Command, _ []string) error {
	proj, _ := cmd.Flags().GetString("project")
	guide := generateAIGuide(environmentNote(proj))
	out, _ := cmd.Flags().GetString("output")
	if out == "" {
		outf("%s", guide)
		return nil
	}
	if err := os.WriteFile(out, []byte(guide), fsmode.File); err != nil {
		return err
	}
	// --claude: рядом с руководством кладём CLAUDE.md-указатель (Claude Code
	// авто-загружает его) — чтобы ИИ сразу видел инструменты без подсказок.
	if withClaude, _ := cmd.Flags().GetBool("claude"); withClaude {
		claudePath := filepath.Join(filepath.Dir(out), "CLAUDE.md")
		if _, err := os.Stat(claudePath); os.IsNotExist(err) {
			if werr := os.WriteFile(claudePath, []byte(claudePointer), fsmode.File); werr != nil {
				return werr
			}
		}
	}
	return nil
}

// uncalledFormEventsGuideBlock — абзац об именах событий, которые платформа
// принимает, но не вызывает (#1153). Перечень берётся из metadata, а не пишется
// здесь словами: рукописная копия отставала бы молча, и руководство обещало бы
// проверку, которой нет, — ровно та беда, ради которой #1151 переносила таблицу
// браузерных событий в metadata. Реализуют событие — абзац укоротится сам.
func uncalledFormEventsGuideBlock() string {
	events := metadata.UncalledFormEvents()
	if len(events) == 0 {
		return ""
	}
	names := make([]string, 0, len(events))
	for _, event := range events {
		names = append(names, "`"+string(event)+"`")
	}
	return `**А эти имена платформа принимает, но не вызывает:** ` + strings.Join(names, ", ") + `.
Их знает конвертер 1С, их принимает ` + "`onebase check`" + `, обработчик пишется и проходит
проверку — но вызывающей стороны в движке нет, и процедура не выполнится ни разу.
«Обработчик не работает, и ошибки нет» — обычно про это; ` + "`onebase check`" + ` печатает о
таком обработчике предупреждение ` + "`form.event-not-dispatched`" + `. Замены закрытию и
активации формы нет: платформа их не отслеживает. Заполнение нового объекта — хук
ПриСозданииНового модуля объекта (не формы) и ключ default у поля; результат
диалога подбора — событие ` + "`Выбор`" + `.
`
}

