package cli

import (
	"fmt"
	"os"
)

// Вывод сообщений CLI в stdout.
//
// Ошибка записи в stdout означает, что получатель вывода исчез: закрытый пайп
// (`onebase ... | head`), отключённый терминал. Сообщить о ней некуда — сломан
// сам канал сообщений, — а прерывать уже выполненную работу поздно и вредно:
// бэкап создан, миграция применена, пользователь про это просто не узнает.
//
// Поэтому решение «ошибку записи в stdout не обрабатываем» принимается здесь
// ОДИН раз и явно, вместо того чтобы молча повторяться в каждой команде. План
// 109 прямо запрещает и россыпь `_ =` по местам вызова, и подавление `fmt`
// целиком в конфиге линтера: оба варианта скрывают решение, это — фиксирует.
//
// Почему `_, _ =`, а не предписанный планом `//nolint:errcheck`: директива не
// действует в режиме `--new-from-merge-base`, на котором построен changed-code
// gate из этапа 109C. Проверено обеими формами — и на отдельной строке, и на
// той же: обычный прогон их принимает, gate по-прежнему сообщает о находке, и
// PR не проходит. Явное присваивание в пустышку работает в обоих режимах и
// здесь не «голое»: оно единственное на пакет и обосновано этим комментарием.
//
// Для вывода, который должен влиять на результат (файлы, HTTP-ответы, отчёты),
// эти функции НЕ предназначены: там ошибку нужно возвращать вызывающему коду.

// outf печатает форматированное сообщение в stdout.
func outf(format string, a ...any) {
	// Ошибка не обрабатывается сознательно — обоснование в комментарии к файлу.
	_, _ = fmt.Fprintf(os.Stdout, format, a...)
}

// outln печатает сообщение в stdout с переводом строки.
func outln(a ...any) {
	// Ошибка не обрабатывается сознательно — обоснование в комментарии к файлу.
	_, _ = fmt.Fprintln(os.Stdout, a...)
}
