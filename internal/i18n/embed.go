package i18n

import "embed"

// EmbeddedLocales — встроенные словари. Два яруса:
//
//	locales/<lang>.json          — перевод, за который отвечает человек;
//	locales/machine/<lang>.json  — машинный перевод, носителем не проверенный.
//
// Машинный ярус грузится первым, поэтому человеческий перевод того же ключа
// всегда побеждает (см. loadFS). Разделение — не украшение: без него после
// массового прохода нельзя отличить проверенную строку от сгенерированной,
// и «переведено на 13 языков» перестаёт что-либо значить (#960). Ревью
// носителем = перенос строки в locales/<lang>.json.
//
//go:embed locales/*.json locales/machine/*.json
var EmbeddedLocales embed.FS
