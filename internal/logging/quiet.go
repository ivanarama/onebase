package logging

import (
	"errors"
	"io"
	"os"
)

// Помощники для вторичных ошибок: закрытие читающей стороны и удаление
// временных путей.
//
// План 109 запрещает механически превращать такие места в `_ =`: без пояснения
// непонятно, решение это или недосмотр. Но и возвращать их вызывающему нельзя —
// к моменту уборки данные уже прочитаны, а если операция провалилась, наверх
// идёт её собственная причина, и подменять её вторичной значит потерять
// настоящую.
//
// Крупные пакеты (launcher, ui, storage, backup, cli) держат свои варианты с
// пакетной формулировкой. Эти два — для остальных, где одна-две таких точки на
// пакет и заводить отдельный файл несоразмерно.
//
// Граница: Close ПИШУЩЕЙ стороны сюда не относится. Там Close сбрасывает буфер,
// и его ошибка означает усечённый файл — она обязана дойти до вызывающего.

// CloseQuiet закрывает читающую сторону, отмечая неудачу в журнале компонента.
func CloseQuiet(component, what string, c io.Closer) {
	if err := c.Close(); err != nil {
		Component(component).Debug("не удалось закрыть "+what, "err", err)
	}
}

// RemoveQuiet удаляет временный файл или каталог; отсутствие — не ошибка.
func RemoveQuiet(component, path string) {
	if err := os.RemoveAll(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		Component(component).Debug("не удалось удалить временный путь", "path", path, "err", err)
	}
}
