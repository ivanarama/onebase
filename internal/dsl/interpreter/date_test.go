// Число(Дата) даёт ГГГГММДДЧЧММСС и возвращается обратно через Дата(число).
// Раньше молча возвращался 0 — и это читалось как «дата пустая» (issue #707).
func TestDate_ToNumberRoundTrip(t *testing.T) {
	r := evalBreakFunc(t, `Функция Тест()
  Возврат Число(Дата(2026, 5, 11, 10, 30, 45));
КонецФункции`)
	if got := fmt.Sprintf("%v", r); got != "20260511103045" {
		t.Errorf("Число(Дата) = %v, ожидалось 20260511103045", got)
	}
	back := evalBreakFunc(t, `Функция Тест()
  Возврат Дата(Число(Дата(2026, 5, 11, 10, 30, 45)));
КонецФункции`)
	d, ok := back.(time.Time)
	if !ok {
		t.Fatalf("Дата(Число(Дата)) вернула %T", back)
	}
	if d.Year() != 2026 || d.Month() != 5 || d.Day() != 11 || d.Hour() != 10 || d.Minute() != 30 || d.Second() != 45 {
		t.Errorf("Дата(Число(Дата)) = %v — round-trip потерял значение", d)
	}
}

