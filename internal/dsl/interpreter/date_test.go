// Форматирование даты через ДФ=. До правки месяц не подставлялся НИ ПРИ КАКОМ
// шаблоне: строка формата целиком понижается в регистре, поэтому замена искала
// «MM» и никогда не срабатывала — «ДФ=dd.MM.yyyy» давало «19.mm.2026».
func TestDate_Format(t *testing.T) {
	cases := []struct {
		pattern string
		want    string
	}{
		{"ДФ=dd.MM.yyyy", "19.08.2026"},   // документировано в langref
		{"ДФ=dd.mm.yyyy", "19.08.2026"},   // то же в нижнем регистре
		{"ДФ='dd.MM.yyyy'", "19.08.2026"}, // кавычечная форма из Plans/36
		{"DF=dd.MM.yyyy", "19.08.2026"},   // латинский ключ
		{"ДФ=yyyy-MM-dd", "2026-08-19"},
		{"ДФ=dd.MM.yy", "19.08.26"},
		{"ДФ=MM", "08"},
		{"ДФ=yyyy", "2026"}, // yyyy заменяется раньше yy, иначе вышло бы «0606»
	}
	for _, c := range cases {
		r := evalBreakFunc(t, `Функция Тест()
  Возврат Формат(Дата(2026, 8, 19), "`+c.pattern+`");
КонецФункции`)
		if r != c.want {
			t.Errorf("Формат(%s) = %v, ожидалось «%s»", c.pattern, r, c.want)
		}
	}
}

// Время в шаблоне ДФ=. Прежний тест фиксировал ОТСУТСТВИЕ поддержки: «ДФ=HH:mm:ss»
// давало «hh:08:ss» — часы литералом, номер месяца на месте минут. Он же требовал
// пересмотреть решение целиком, когда время появится, — что здесь и сделано.
//
// Токены теперь регистрозависимы, как в 1С (MM — месяц, mm — минуты, HH — часы),
// и понимаются русские написания. Совместимость: строчное «mm» читается минутами
// ТОЛЬКО в шаблоне с часами — иначе это по-прежнему месяц, и «дд.мм.гггг» из
// существующих конфигураций печатает то же, что и раньше (см. TestDate_Format).
func TestDate_FormatTime(t *testing.T) {
	cases := []struct {
		pattern string
		want    string
	}{
		{"ДФ=HH:mm:ss", "14:37:05"},
		{"ДФ=dd.MM.yyyy HH:mm", "19.08.2026 14:37"},
		{"ДФ=dd.MM.yyyy HH:mm:ss", "19.08.2026 14:37:05"},
		// Русские написания токенов — наравне с латинскими.
		{"ДФ=дд.ММ.гггг ЧЧ:мм:сс", "19.08.2026 14:37:05"},
		// 12-часовые часы: 14:37 → 02.
		{"ДФ=hh:mm", "02:37"},
		// Без часов строчное «mm» остаётся МЕСЯЦЕМ — прежнее поведение.
		{"ДФ=dd.mm.yyyy", "19.08.2026"},
		{"ДФ=мм", "08"},
		// Явный верхний регистр — всегда месяц, даже рядом с часами.
		{"ДФ=HH MM", "14 08"},
		// Unicode-приведение регистра ключа не должно менять регистр значения.
		{"ДФ=İ dd.MM.yyyy HH:mm", "İ 19.08.2026 14:37"},
	}
	for _, c := range cases {
		r := evalBreakFunc(t, `Функция Тест()
  Возврат Формат(Дата(2026, 8, 19, 14, 37, 5), "`+c.pattern+`");
КонецФункции`)
		if r != c.want {
			t.Errorf("Формат(%s) = %v, ожидалось «%s»", c.pattern, r, c.want)
		}
	}
}
