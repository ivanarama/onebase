// ДобавитьЧас/ДобавитьМинуту/ДобавитьСекунду — сдвиг внутри суток (issue #707).
// До них единственным работающим приёмом был `Дата + N`, а ДобавитьДень с
// дробным аргументом молча давал нулевой сдвиг.
func TestDate_AddTimeUnits(t *testing.T) {
	cases := []struct {
		expr    string
		h, m, s int
		day     int
	}{
		{`ДобавитьЧас(Дата(2026, 5, 11, 10, 30, 0), 2)`, 12, 30, 0, 11},
		{`ДобавитьЧас(Дата(2026, 5, 11, 10, 30, 0), -11)`, 23, 30, 0, 10},
		{`ДобавитьМинуту(Дата(2026, 5, 11, 10, 30, 0), 45)`, 11, 15, 0, 11},
		{`ДобавитьСекунду(Дата(2026, 5, 11, 10, 30, 0), 90)`, 10, 31, 30, 11},
		{`ДобавитьСекунд(Дата(2026, 5, 11, 10, 30, 0), -30)`, 10, 29, 30, 11},
		// Дробная часть учитывается — в отличие от ДобавитьДень.
		{`ДобавитьМинуту(Дата(2026, 5, 11, 10, 30, 0), 0.5)`, 10, 30, 30, 11},
		{`ДобавитьЧасов(Дата(2026, 5, 11, 10, 30, 0), 1.5)`, 12, 0, 0, 11},
	}
	for _, c := range cases {
		r := evalBreakFunc(t, "Функция Тест()\n  Возврат "+c.expr+";\nКонецФункции")
		d, ok := r.(time.Time)
		if !ok {
			t.Fatalf("%s вернул %T, ожидался time.Time", c.expr, r)
		}
		if d.Day() != c.day || d.Hour() != c.h || d.Minute() != c.m || d.Second() != c.s {
			t.Errorf("%s = %v, ожидалось %02d-е %02d:%02d:%02d", c.expr, d, c.day, c.h, c.m, c.s)
		}
	}
}

