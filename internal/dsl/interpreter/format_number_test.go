package interpreter

import "testing"

// Формат числа — как в 1С. Без ЧДЦ печатается столько знаков, сколько есть
// в значении (раньше всегда два: номер дня «16.00», год «2 026.00»), а ЧГ=0
// отключает группировку разрядов (раньше ключ не читался вовсе).
func TestFormat_NumberLike1C(t *testing.T) {
	cases := []struct {
		expr string
		want string
	}{
		{`Формат(21, "ЧГ=0")`, "21"},
		{`Формат(2026, "ЧГ=0")`, "2026"},
		{`Формат(2026, "")`, "2 026"},
		{`Формат(21.5, "ЧГ=0")`, "21.5"},
		{`Формат(1234567.25, "")`, "1 234 567.25"},
		{`Формат(0.1 + 0.2, "ЧГ=0")`, "0.3"},
		{`Формат(-1500, "")`, "-1 500"},
		// С ЧДЦ — как раньше: ровно столько знаков.
		{`Формат(21, "ЧДЦ=2")`, "21.00"},
		{`Формат(1234.567, "ЧДЦ=2; ЧРГ=' '")`, "1 234.57"},
		{`Формат(1234.5, "ЧДЦ=0; ЧГ=0")`, "1235"},
		{`Формат(1234.5, "ЧДЦ=1; ЧРГ=','")`, "1,234.5"},
	}
	for _, c := range cases {
		r := evalBreakFunc(t, `Функция Тест()
  Возврат `+c.expr+`;
КонецФункции`)
		if r != c.want {
			t.Errorf("%s = %v, ожидалось «%s»", c.expr, r, c.want)
		}
	}
}
