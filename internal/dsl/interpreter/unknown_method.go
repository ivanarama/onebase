package interpreter

import (
	"sort"
	"strings"
)

// Вызов несуществующего метода — ошибка, а не тихий возврат Неопределено.
//
// Прежде `М.СовсемНетТакогоМетода(5)` молча возвращал Неопределено и шёл
// дальше: опечатка в имени метода или неверный тип значения превращались в
// бесшумную потерю функциональности. Стоило это, среди прочего, молча
// неработающей ретенции, которая при этом рапортовала об успехе (#718).
//
// ГРАНИЦА, которую важно понимать. Здесь закрыты типы, у которых метод ищет
// собственный switch этого пакета: Массив, Структура, Соответствие. Плюс в
// диспетчере закрыт случай «у типа значения методов нет вовсе» (строка, число,
// дата, булево) — он общий и работает для всего.
//
// Не закрыты остальные ~45 реализаций CallMethod (таблица значений, табличный
// документ, диаграмма, HTTP, файлы, прокси документов и справочников и т.д.):
// каждая решает про имя метода сама и об «не нашёл» наружу не сообщает — чтобы
// это изменить, нужен другой контракт MethodCallable, а не правка по месту.
// Пока такой вызов у них по-прежнему тих. Список закрытых типов держится
// рядом с их switch'ами намеренно: разъехавшись, он сам станет источником
// ложных ошибок.
var (
	arrayMethods = []string{
		"Добавить", "Количество", "Получить", "Установить", "Удалить",
		"Очистить", "Вставить", "Найти", "Сортировать",
	}
	structMethods = []string{"Вставить", "Удалить", "Количество", "Свойство"}
	mapMethods    = []string{
		"Вставить", "Получить", "Удалить", "Количество", "Очистить",
	}
)

// unknownMethod поднимает ошибку с именем типа, именем метода и списком
// доступных. Список важнее, чем кажется: ошибаются почти всегда в написании
// («ДобавитьСтроку» вместо «Добавить»), и без перечисления следующий шаг —
// поход в документацию.
func unknownMethod(typeName, method string, known []string) {
	list := append([]string(nil), known...)
	sort.Strings(list)
	RaiseUserError("Метод " + method + " не существует у значения типа " + typeName +
		"; доступны: " + strings.Join(list, ", "))
}
