package interpreter_test

// Незаполненное число в сравнении — ноль (#1136).
//
// Пустая ячейка числа доезжает до модуля как nil: форма отдаёт её так, в базу
// уходит NULL, оттуда же читается обратно. Числовая ветка сравнения nil не
// принимала, и всё уходило в строковый ключ — «<nil>» против «0». Отсюда
// `Стр.Цена = 0` → Ложь при невведённой цене, то есть идиома 1С, на которой
// стоит половина прикладного кода, молча не срабатывала.
//
// Строковый ключ ломал и порядок: «<nil>» лексикографически больше любой цифры,
// поэтому `Цена > 0` и `Цена > 5` давали Истину. Правило поэтому одно на «=» и
// на «<»/«>» — иначе после починки равенства `Цена = 0` и `Цена > 0` были бы
// истинны одновременно.
//
// evalWithVars объявлена в date_equality_test.go — соседняя починка того же
// сравнения (#1034); переменные инжектируются ровно так, как значения приходят
// в модуль из результата запроса или из объекта.

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/ivantit66/onebase/internal/dsl/interpreter"
)

// nilNumberVars — незаполненное число рядом с заполненным: правило обязано
// менять поведение только первого.
func nilNumberVars() map[string]any {
	return map[string]any{"Цена": nil, "Количество": float64(2)}
}

func evalExpr1136(t *testing.T, expr string, vars map[string]any) any {
	t.Helper()
	return evalWithVars(t, "Функция Т()\n  Возврат "+expr+";\nКонецФункции", vars)
}

func TestNilNumericComparison_ПустоеЧислоЭтоНоль_1136(t *testing.T) {
	cases := []struct {
		name string
		expr string
		want any
	}{
		{"равно нулю", `Цена = 0`, true},
		{"ноль слева", `0 = Цена`, true},
		{"не равно нулю — Ложь", `Цена <> 0`, false},
		{"равно другому числу — Ложь", `Цена = 5`, false},
		{"не равно другому числу — Истина", `Цена <> 5`, true},
		{"равно заполненному соседу — Ложь", `Цена = Количество`, false},

		// Порядок: до починки «<nil>» был больше любой цифры.
		{"больше нуля — Ложь", `Цена > 0`, false},
		{"меньше нуля — Ложь", `Цена < 0`, false},
		{"не меньше нуля", `Цена >= 0`, true},
		{"не больше нуля", `Цена <= 0`, true},
		{"меньше положительного", `Цена < 5`, true},
		{"больше положительного — Ложь", `Цена > 5`, false},
		{"больше отрицательного", `Цена > -5`, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, evalExpr1136(t, tc.expr, nilNumberVars()))
		})
	}
}

// Симптом из заявки целиком: ветка автоподстановки цены выбирается по
// `Цена = 0` и обязана сработать у новой строки. Заодно — что `> 0` и `= 0`
// больше не истинны одновременно.
func TestNilNumericComparison_ВеткаПодстановкиЦены_1136(t *testing.T) {
	src := `Функция Т()
  Если Цена = 0 Тогда
    Возврат "подставляем";
  ИначеЕсли Цена > 0 Тогда
    Возврат "цена введена";
  КонецЕсли;
  Возврат "ни туда ни сюда";
КонецФункции`
	assert.Equal(t, "подставляем", evalWithVars(t, src, nilNumberVars()))
}

// Правило одностороннее: вторая сторона обязана быть числом. Иначе починка
// превратилась бы в «nil равен чему угодно пустому».
func TestNilNumericComparison_НечисловыеСравненияНеТронуты_1136(t *testing.T) {
	vars := map[string]any{"Цена": nil, "Пусто": "", "Флаг": false}
	cases := []struct {
		name string
		expr string
		want any
	}{
		{"пустая строка не ноль", `Цена = Пусто`, false},
		{"литерал пустой строки", `Цена = ""`, false},
		{"строка «0» сравнивается как раньше", `Цена = "0"`, false},
		{"Ложь не ноль", `Цена = Флаг`, false},
		{"nil равен nil", `Цена = Цена`, true},
		{"ноль не пустая строка", `0 = Пусто`, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, evalExpr1136(t, tc.expr, vars))
		})
	}
}

// ЗначениеЗаполнено ничего не теряет — и ничего не приобретает. Отличить
// «не введено» от «введён ноль» им было нельзя и до починки: для 1С ноль сам по
// себе незаполненное значение. Тест закрепляет это прямо, чтобы правку не
// прочитали как утрату единственного способа различить эти случаи.
func TestNilNumericComparison_ЗначениеЗаполненоНеРазличаетНольИПустоту_1136(t *testing.T) {
	src := `Функция Т()
  Возврат Строка(ЗначениеЗаполнено(Цена)) + "/" + Строка(ЗначениеЗаполнено(0)) + "/" + Строка(ЗначениеЗаполнено(Количество));
КонецФункции`
	assert.Equal(t, "false/false/true", evalWithVars(t, src, nilNumberVars()))
}

// Граница правила: оно живёт на пути операторов и НЕ дотягивается до поиска по
// коллекциям. Тот же comparator обслуживает Массив.Найти и
// ТаблицаЗначений.Найти/НайтиСтроки, поэтому подстановка внутри compareSandboxed
// (так было в первом круге) отбирала бы незаполненные строки по «Цена = 0», а
// заполненные нули — по отбору на Неопределено. Оба естественных способа
// разделить «пусто» и «ноль» ломались разом, причём Соответствие с его refKey
// продолжало их различать — платформа расходилась сама с собой.
func TestNilNumericComparison_ПоискПоКоллекциямНеТронут_1136(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want any
	}{
		{
			// Отбор нулей не должен приносить незаполненные строки.
			name: "НайтиСтроки(Цена=0) не находит незаполненную",
			src: `Функция Т()
  Т = Новый ТаблицаЗначений;
  Т.Колонки.Добавить("Цена");
  Т.Добавить();
  Возврат Т.НайтиСтроки(Новый Структура("Цена", 0)).Количество();
КонецФункции`,
			want: float64(0),
		},
		{
			// Обратное направление: отбор незаполненных не должен приносить нули.
			// Это и есть штатный способ найти строки без введённого числа.
			name: "НайтиСтроки(Цена=Неопределено) не находит ноль",
			src: `Функция Т()
  Т = Новый ТаблицаЗначений;
  Т.Колонки.Добавить("Цена");
  Стр = Т.Добавить();
  Стр.Цена = 0;
  Возврат Т.НайтиСтроки(Новый Структура("Цена", Неопределено)).Количество();
КонецФункции`,
			want: float64(0),
		},
		{
			name: "ТЗ.Найти(0) не находит незаполненную строку",
			src: `Функция Т()
  Т = Новый ТаблицаЗначений;
  Т.Колонки.Добавить("Цена");
  Т.Добавить();
  Возврат Т.Найти(0) = Неопределено;
КонецФункции`,
			want: true,
		},
		{
			// Найти возвращает Неопределено, когда не нашёл. Сравнивать результат
			// с нулём тут нельзя (см. тест ниже), поэтому спрашиваем тип.
			name: "Массив.Найти(Неопределено) не находит ноль",
			src: `Функция Т()
  М = Новый Массив;
  М.Добавить(0);
  Возврат Строка(ТипЗнч(М.Найти(Неопределено)));
КонецФункции`,
			want: "Неопределено",
		},
		{
			name: "Массив.Найти(0) не находит незаполненное",
			src: `Функция Т()
  М = Новый Массив;
  М.Добавить(Неопределено);
  Возврат Строка(ТипЗнч(М.Найти(0)));
КонецФункции`,
			want: "Неопределено",
		},
		{
			// Ключи Соответствия ходят через refKey и правилу не подчиняются —
			// как было заявлено с самого начала.
			name: "Соответствие.Получить(0) не берёт значение пустого ключа",
			src: `Функция Т()
  С = Новый Соответствие;
  С.Вставить(Неопределено, "пусто");
  Возврат ТипЗнч(С.Получить(0)) = ТипЗнч(Неопределено);
КонецФункции`,
			want: true,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, evalWithVars(t, tc.src, nil))
		})
	}
}

// Цена варианта 2, названная прямо. Найти/Получить/НайтиПоНаименованию отдают
// Неопределено, когда ничего не нашли, а `Неопределено = 0` теперь Истина —
// значит `Если Инд = 0` больше не отличает «не найдено» от «найдено первым», и
// `Если Инд = Неопределено` тоже (ноль ему равен). В 1С обе проверки работают,
// то есть здесь расхождение с 1С в сторону, обратную починяемой; принято вместе
// с вариантом 2 (решение по #1136) и закреплено тестом, чтобы следующий читатель
// видел это как выбор, а не как недосмотр. Рабочий признак — ТипЗнч.
func TestNilNumericComparison_НеНайденоБольшеНеОтличаетсяЧерезРавенство_1136(t *testing.T) {
	const list = `  М = Новый Массив;
  М.Добавить("а");
`
	t.Run("сравнение с нулём не отличает не найдено от индекса 0", func(t *testing.T) {
		src := `Функция Т()
` + list + `  Возврат Строка(М.Найти("нет") = 0) + "/" + Строка(М.Найти("а") = 0);
КонецФункции`
		assert.Equal(t, "true/true", evalWithVars(t, src, nil))
	})

	t.Run("сравнение с Неопределено тоже не отличает", func(t *testing.T) {
		src := `Функция Т()
` + list + `  Возврат Строка(М.Найти("нет") = Неопределено) + "/" + Строка(М.Найти("а") = Неопределено);
КонецФункции`
		assert.Equal(t, "true/true", evalWithVars(t, src, nil))
	})

	t.Run("ТипЗнч отличает", func(t *testing.T) {
		src := `Функция Т()
` + list + `  Возврат Строка(ТипЗнч(М.Найти("нет"))) + "/" + Строка(ТипЗнч(М.Найти("а")));
КонецФункции`
		assert.Equal(t, "Неопределено/Число", evalWithVars(t, src, nil))
	})
}

// Утверждения сравнивают тем же правилом, что и оператор.
//
// equal() — путь объекта «Утверждать» (Равно/НеРавно, МаскаПоля), и он
// намеренно зовёт equalOperator, а не equalSandboxed: самопроверка конфигурации
// обязана видеть ровно то, что увидит модуль, иначе `Утверждать.Равно(Стр.Цена,
// 0)` краснел бы там, где `Если Стр.Цена = 0` выбирает ветку. Решение держалось
// на одном абзаце в описании PR: возврат equal() на equalSandboxed не ронял ни
// одного теста во всём пакете — то есть следующий рефакторинг снял бы его молча.
// Здесь оно сторожится.
//
// Путь публичный: объект кладётся в extraVars и зовётся из DSL — ровно так его
// инжектирует раннер тестов (internal/ui/testrun.go), и записанный рекордером
// исход — то самое, по чему раннер решает, прошёл тест или упал.
type assertLog1136 struct{ outcomes []interpreter.AssertOutcome }

func (r *assertLog1136) RecordAssert(o interpreter.AssertOutcome) {
	r.outcomes = append(r.outcomes, o)
}

// assertPassed1136 исполняет тело DSL с ровно одним утверждением и отдаёт его
// исход.
func assertPassed1136(t *testing.T, body string, vars map[string]any) bool {
	t.Helper()
	rec := &assertLog1136{}
	extra := map[string]any{"Утверждать": interpreter.NewAssertRoot(rec)}
	for k, v := range vars {
		extra[k] = v
	}
	evalWithVars(t, "Функция Т()\n"+body+"\n  Возврат 0;\nКонецФункции", extra)
	require.Len(t, rec.outcomes, 1, "ожидалось ровно одно записанное утверждение")
	return rec.outcomes[0].Passed
}

func TestNilNumericComparison_УтверждатьСогласованоСОператором_1136(t *testing.T) {
	cases := []struct {
		name   string
		fact   string
		expect string
		want   bool // и у оператора, и у утверждения
	}{
		{"незаполненное против нуля", "Цена", "0", true},
		{"ноль слева", "0", "Цена", true},
		{"незаполненное против другого числа", "Цена", "5", false},
		{"заполненное против нуля", "Количество", "0", false},
		{"незаполненное против пустой строки", "Цена", `""`, false},
		{"незаполненное против незаполненного", "Цена", "Цена", true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			pair := tc.fact + ", " + tc.expect
			assert.Equal(t, tc.want, evalExpr1136(t, tc.fact+" = "+tc.expect, nilNumberVars()),
				"оператор «=»")
			assert.Equal(t, tc.want,
				assertPassed1136(t, `  Утверждать.Равно(`+pair+`, "проверка");`, nilNumberVars()),
				"Утверждать.Равно обязано отвечать так же, как оператор «=»")
			assert.Equal(t, !tc.want,
				assertPassed1136(t, `  Утверждать.НеРавно(`+pair+`, "проверка");`, nilNumberVars()),
				"Утверждать.НеРавно — отрицание того же правила")
		})
	}
}

// Радиус решения, названный прямо: у прикладной конфигурации утверждения вокруг
// нуля меняют исход после обновления. Тест закрепляет обе стороны цены — и
// «начнёт падать», и «перестанет различать», — чтобы это читалось как выбор, а
// не как недосмотр.
func TestNilNumericComparison_УтверждатьБольшеНеОтличаетНольОтПустоты_1136(t *testing.T) {
	const list = `  М = Новый Массив;
  М.Добавить("а");
`
	t.Run("НеРавно(не найдено, 0) как проверка «нашлось» проваливается", func(t *testing.T) {
		assert.False(t, assertPassed1136(t,
			list+`  Утверждать.НеРавно(М.Найти("нет"), 0, "нашлось");`, nil))
	})

	t.Run("Равно(…, 0) проходит и на нуле, и на незаполненном", func(t *testing.T) {
		vars := nilNumberVars()
		assert.True(t, assertPassed1136(t, `  Утверждать.Равно(Цена, 0, "ноль");`, vars),
			"незаполненное")
		assert.True(t, assertPassed1136(t, `  Утверждать.Равно(0, 0, "ноль");`, vars),
			"настоящий ноль")
	})

	// Рабочий признак «не найдено» для самопроверки — тот же, что и для модуля.
	t.Run("ТипЗнч отличает и в утверждении", func(t *testing.T) {
		assert.True(t, assertPassed1136(t,
			list+`  Утверждать.Равно(Строка(ТипЗнч(М.Найти("нет"))), "Неопределено", "не найдено");`, nil))
	})
}
