package interpreter_test

// Незаполненное число в сравнении — ноль (#1136).
//
// Пустая ячейка числа доезжает до модуля как nil: форма отдаёт её так, в базу
// уходит NULL, оттуда же читается обратно. Числовая ветка сравнения nil не
// принимала, и всё уходило в строковый ключ — «<nil>» против «0». Отсюда
// `Стр.Цена = 0` → Ложь при невведённой цене, то есть идиома 1С, на которой
// стоит половина прикладного кода, молча не срабатывала.
//
// Строковый ключ ломал и порядок: «<nil>» лексикографически больше любой цифры,
// поэтому `Цена > 0` и `Цена > 5` давали Истину. Правило поэтому одно на «=» и
// на «<»/«>» — иначе после починки равенства `Цена = 0` и `Цена > 0` были бы
// истинны одновременно.
//
// evalWithVars объявлена в date_equality_test.go — соседняя починка того же
// сравнения (#1034); переменные инжектируются ровно так, как значения приходят
// в модуль из результата запроса или из объекта.

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

// nilNumberVars — незаполненное число рядом с заполненным: правило обязано
// менять поведение только первого.
func nilNumberVars() map[string]any {
	return map[string]any{"Цена": nil, "Количество": float64(2)}
}

func evalExpr1136(t *testing.T, expr string, vars map[string]any) any {
	t.Helper()
	return evalWithVars(t, "Функция Т()\n  Возврат "+expr+";\nКонецФункции", vars)
}

func TestNilNumericComparison_ПустоеЧислоЭтоНоль_1136(t *testing.T) {
	cases := []struct {
		name string
		expr string
		want any
	}{
		{"равно нулю", `Цена = 0`, true},
		{"ноль слева", `0 = Цена`, true},
		{"не равно нулю — Ложь", `Цена <> 0`, false},
		{"равно другому числу — Ложь", `Цена = 5`, false},
		{"не равно другому числу — Истина", `Цена <> 5`, true},
		{"равно заполненному соседу — Ложь", `Цена = Количество`, false},

		// Порядок: до починки «<nil>» был больше любой цифры.
		{"больше нуля — Ложь", `Цена > 0`, false},
		{"меньше нуля — Ложь", `Цена < 0`, false},
		{"не меньше нуля", `Цена >= 0`, true},
		{"не больше нуля", `Цена <= 0`, true},
		{"меньше положительного", `Цена < 5`, true},
		{"больше положительного — Ложь", `Цена > 5`, false},
		{"больше отрицательного", `Цена > -5`, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, evalExpr1136(t, tc.expr, nilNumberVars()))
		})
	}
}

// Симптом из заявки целиком: ветка автоподстановки цены выбирается по
// `Цена = 0` и обязана сработать у новой строки. Заодно — что `> 0` и `= 0`
// больше не истинны одновременно.
func TestNilNumericComparison_ВеткаПодстановкиЦены_1136(t *testing.T) {
	src := `Функция Т()
  Если Цена = 0 Тогда
    Возврат "подставляем";
  ИначеЕсли Цена > 0 Тогда
    Возврат "цена введена";
  КонецЕсли;
  Возврат "ни туда ни сюда";
КонецФункции`
	assert.Equal(t, "подставляем", evalWithVars(t, src, nilNumberVars()))
}

// Правило одностороннее: вторая сторона обязана быть числом. Иначе починка
// превратилась бы в «nil равен чему угодно пустому».
func TestNilNumericComparison_НечисловыеСравненияНеТронуты_1136(t *testing.T) {
	vars := map[string]any{"Цена": nil, "Пусто": "", "Флаг": false}
	cases := []struct {
		name string
		expr string
		want any
	}{
		{"пустая строка не ноль", `Цена = Пусто`, false},
		{"литерал пустой строки", `Цена = ""`, false},
		{"строка «0» сравнивается как раньше", `Цена = "0"`, false},
		{"Ложь не ноль", `Цена = Флаг`, false},
		{"nil равен nil", `Цена = Цена`, true},
		{"ноль не пустая строка", `0 = Пусто`, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, evalExpr1136(t, tc.expr, vars))
		})
	}
}

// ЗначениеЗаполнено ничего не теряет — и ничего не приобретает. Отличить
// «не введено» от «введён ноль» им было нельзя и до починки: для 1С ноль сам по
// себе незаполненное значение. Тест закрепляет это прямо, чтобы правку не
// прочитали как утрату единственного способа различить эти случаи.
func TestNilNumericComparison_ЗначениеЗаполненоНеРазличаетНольИПустоту_1136(t *testing.T) {
	src := `Функция Т()
  Возврат Строка(ЗначениеЗаполнено(Цена)) + "/" + Строка(ЗначениеЗаполнено(0)) + "/" + Строка(ЗначениеЗаполнено(Количество));
КонецФункции`
	assert.Equal(t, "false/false/true", evalWithVars(t, src, nilNumberVars()))
}
