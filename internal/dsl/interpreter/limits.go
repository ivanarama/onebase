package interpreter

// Лимиты безопасности интерпретатора. Сессия onebase однопоточная: runaway-код
// заблокировал бы всю работу платформы, а бесконтрольная рекурсия переполнила бы
// стек горутины и аварийно завершила процесс (panic вне досягаемости Попытки).
// Значения заведомо больше любых реальных прикладных расчётов.
const (
	// maxWhileIter — потолок итераций одного цикла «Пока». Защита от зацикливания.
	maxWhileIter = 50_000_000

	// defaultMaxRecursionDepth — глубина вложенных вызовов процедур/функций по
	// умолчанию. Без лимита бесконечная рекурсия растит стек горутины до краха
	// процесса (panic вне досягаемости Попытки). Прикладной код её не достигает.
	// Переопределяется через Interpreter.MaxRecursionDepth (напр. в тестах).
	defaultMaxRecursionDepth = 1000

	// defaultMaxEvalDepth ограничивает отдельно вложенные Вычислить/Eval.
	// Динамическое выражение исполняется в том же кадре процедуры и потому не
	// увеличивает обычную глубину вызовов; без отдельного счётчика конструкция
	// `Текст = "Вычислить(Текст)"; Вычислить(Текст)` переполняет стек Go.
	defaultMaxEvalDepth = 100
)
