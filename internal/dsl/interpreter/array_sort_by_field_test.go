func runDSL1438(t *testing.T, src string) any {
	t.Helper()
	var result any
	require.NoError(t, interpreter.New().RunSandboxed(parseProc(t, src), nil, interpreter.SandboxProfile{}, &result))
	return result
}

// Основной сценарий заявки: массив структур, собранный из нескольких
// источников, упорядочивается по полю без ручной сортировки слиянием.
func TestArraySortByField_SingleKey(t *testing.T) {
	src := `Процедура Тест()
  М = Новый Массив;
  М.Добавить(Новый Структура("Номер, Дата", 3, Дата(2026,1,3)));
  М.Добавить(Новый Структура("Номер, Дата", 1, Дата(2026,1,1)));
  М.Добавить(Новый Структура("Номер, Дата", 2, Дата(2026,1,2)));
  М.СортироватьПоПолю("Дата");
  Р = "";
  Для Каждого С Из М Цикл
    Р = Р + Строка(С.Номер);
  КонецЦикла;
  Возврат Р;
КонецПроцедуры`
	assert.Equal(t, "123", fmt.Sprintf("%v", runDSL1438(t, src)))
}

// Направление и многоключевость — те же слова, что у ТаблицаЗначений.
func TestArraySortByField_MultiKeyAndDesc(t *testing.T) {
	src := `Процедура Тест()
  М = Новый Массив;
  М.Добавить(Новый Структура("Группа, Вес", "Б", 1));
  М.Добавить(Новый Структура("Группа, Вес", "А", 1));
  М.Добавить(Новый Структура("Группа, Вес", "А", 9));
  М.СортироватьПоПолю("Группа Возр, Вес Убыв");
  Р = "";
  Для Каждого С Из М Цикл
    Р = Р + Строка(С.Группа) + Строка(С.Вес) + ";";
  КонецЦикла;
  Возврат Р;
КонецПроцедуры`
	assert.Equal(t, "А9;А1;Б1;", fmt.Sprintf("%v", runDSL1438(t, src)))
}

// Главная проверка разбора: одни и те же данные обязаны упорядочиваться
// одинаково в массиве структур и в ТаблицеЗначений. Разойдись разбор
// направления или сравнение — этот тест поймает расхождение (#1438).
func TestArraySortByField_MatchesValueTableOrder(t *testing.T) {
	const rows = `
  Данные = Новый Массив;
  Данные.Добавить(Новый Структура("Имя, Сумма", "в", 10));
  Данные.Добавить(Новый Структура("Имя, Сумма", "а", 30));
  Данные.Добавить(Новый Структура("Имя, Сумма", "б", 30));
`
	arr := runDSL1438(t, `Процедура Тест()`+rows+`
  Данные.СортироватьПоПолю("Сумма Убыв, Имя");
  Р = "";
  Для Каждого С Из Данные Цикл
    Р = Р + Строка(С.Имя);
  КонецЦикла;
  Возврат Р;
КонецПроцедуры`)

	tbl := runDSL1438(t, `Процедура Тест()`+rows+`
  Т = Новый ТаблицаЗначений;
  Т.Колонки.Добавить("Имя");
  Т.Колонки.Добавить("Сумма");
  Для Каждого С Из Данные Цикл
    Стр = Т.Добавить();
    Стр.Имя = С.Имя;
    Стр.Сумма = С.Сумма;
  КонецЦикла;
  Т.Сортировать("Сумма Убыв, Имя");
  Р = "";
  Для Каждого Стр Из Т Цикл
    Р = Р + Строка(Стр.Имя);
  КонецЦикла;
  Возврат Р;
КонецПроцедуры`)

	// Защита от вхолостую зелёного теста: сравнение бессмысленно, если обе
	// ветки вернули пустую строку.
	require.Equal(t, "абв", fmt.Sprintf("%v", tbl), "ТаблицаЗначений упорядочила не так, как ожидалось")
	assert.Equal(t, fmt.Sprintf("%v", tbl), fmt.Sprintf("%v", arr),
		"массив и ТаблицаЗначений упорядочили одни и те же данные по-разному")
}

// Неопределено — законное значение поля и участвует в сравнении, а не роняет
// сортировку: иначе собранные из разных источников строки нельзя упорядочить.
func TestArraySortByField_UndefinedIsAValue(t *testing.T) {
	src := `Процедура Тест()
  М = Новый Массив;
  М.Добавить(Новый Структура("Ключ", 2));
  М.Добавить(Новый Структура("Ключ", Неопределено));
  М.Добавить(Новый Структура("Ключ", 1));
  М.СортироватьПоПолю("Ключ");
  Возврат М.Количество();
КонецПроцедуры`
	assert.Equal(t, "3", fmt.Sprintf("%v", runDSL1438(t, src)))
}

// Чужой элемент и отсутствующее поле — громкая ошибка с номером элемента.
// Тихая подстановка Неопределено дала бы правдоподобный, но неверный порядок.
func TestArraySortByField_LoudErrors(t *testing.T) {
	for _, tc := range []struct{ name, body, want string }{
		{
			name: "элемент не Структура",
			body: `М.Добавить(Новый Структура("Ключ", 1)); М.Добавить("просто строка");`,
			want: "не Структура",
		},
		{
			name: "нет поля",
			body: `М.Добавить(Новый Структура("Ключ", 1)); М.Добавить(Новый Структура("Другое", 2));`,
			want: "нет поля",
		},
		{
			name: "поле не указано",
			body: `М.Добавить(Новый Структура("Ключ", 1));`,
			want: "не указано поле",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			spec := `"Ключ"`
			if tc.name == "поле не указано" {
				spec = `""`
			}
			src := `Процедура Тест()
  М = Новый Массив;
  ` + tc.body + `
  Попытка
    М.СортироватьПоПолю(` + spec + `);
    Возврат "без ошибки";
  Исключение
    Возврат ОписаниеОшибки();
  КонецПопытки;
КонецПроцедуры`
			assert.Contains(t, fmt.Sprintf("%v", runDSL1438(t, src)), tc.want)
		})
	}
}
