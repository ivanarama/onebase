package interpreter_test

// Дата, прочитанная ЗАПРОСОМ, теряла время суток.
//
// Момент хранится в UTC (на запись: t.UTC().Format(RFC3339)), а стенные часы у
// платформы везде локальные. Функции Час/Минута/День брали час прямо из
// хранимого значения, поэтому записанное «17:25» читалось как «14:25», а на
// SQLite колонка даты приходит из запроса СТРОКОЙ — там toTime вообще отдавал
// Неопределено, и Число() превращал это в 0. Прикладным конфигурациям
// приходилось дублировать час отдельным числовым полем при записи.
//
// ПОЯС В ТЕСТАХ ЗАКРЕПЛЁН ЯВНО, и обе стороны сравнения — литералы: и хранимое
// значение, и ожидаемые части даты выписаны константами. Тест, который строит
// ожидание через time.Local и сверяет со значением, полученным через
// time.Local, — тождество: он зелёный в любом поясе и целый класс сдвигов не
// ловит по построению. CI гоняет тесты в UTC, где приведение к локальному
// вообще тождественно, поэтому без закрепления пояса проверять тут нечего.

import (
	"fmt"
	"testing"
	"time"

	"github.com/stretchr/testify/assert"
)

// зона — часовой пояс, закрепляемый на время подтеста, и хранимое значение,
// которое платформа записывает в этом поясе.
type зона struct {
	имя      string
	смещение int
}

// пояса — набор с намеренно разными знаками и некруглыми смещениями. Отрицательные
// нужны отдельно: именно западнее Гринвича перевод полуночи «уезжает» через
// границу суток, и дефекты этого класса на UTC-хосте невидимы.
var пояса = []зона{
	{"UTC", 0},
	{"MSK", 3 * 3600},
	{"NY", -5 * 3600},
	{"NPT", 5*3600 + 45*60},
	{"LINT", 14 * 3600},
}

// закрепитьПояс подменяет time.Local на время подтеста. FixedZone, а не
// LoadLocation: база tzdata на машине может отсутствовать, а поведение обязано
// проверяться везде. Подтесты с закреплением пояса нельзя помечать t.Parallel —
// time.Local глобален.
func закрепитьПояс(t *testing.T, з зона) {
	t.Helper()
	saved := time.Local
	time.Local = time.FixedZone(з.имя, з.смещение)
	t.Cleanup(func() { time.Local = saved })
}

// частьДаты исполняет вызов встроенной функции так, как это делает модуль:
// значение приходит переменной из результата запроса.
func частьДаты(t *testing.T, fn string, значение any) any {
	t.Helper()
	src := fmt.Sprintf("Функция Т()\n  Возврат %s(Прочитано);\nКонецФункции", fn)
	return evalWithVars(t, src, map[string]any{"Прочитано": значение})
}

// форматДаты исполняет Формат через публичный запуск модуля: значение приходит
// переменной в том же виде, в каком его отдаёт результат запроса.
func форматДаты(t *testing.T, значение any) any {
	t.Helper()
	return evalWithVars(t,
		"Функция Т()\n  Возврат Формат(Прочитано, \"ДФ=dd.MM.yyyy\");\nКонецФункции",
		map[string]any{"Прочитано": значение})
}

// Записан момент 29.07.2026 17:25:37 по местному времени. В каждом поясе он
// хранится СВОЕЙ строкой (выписана явно), а читаться обязан одинаково.
func TestДатаИзЗапроса_ВремяСутокСохраняетсяВЛюбомПоясе(t *testing.T) {
	cases := []struct {
		з        зона
		хранимое string
	}{
		{пояса[0], "2026-07-29T17:25:37Z"},
		{пояса[1], "2026-07-29T14:25:37Z"},
		{пояса[2], "2026-07-29T22:25:37Z"},
		{пояса[3], "2026-07-29T11:40:37Z"},
		{пояса[4], "2026-07-29T03:25:37Z"},
	}
	части := map[string]float64{
		"Час": 17, "Минута": 25, "Секунда": 37,
		"Год": 2026, "Месяц": 7, "День": 29,
	}
	for _, c := range cases {
		t.Run(c.з.имя, func(t *testing.T) {
			закрепитьПояс(t, c.з)
			for fn, want := range части {
				got := частьДаты(t, fn, c.хранимое)
				assert.Equal(t, want, got,
					"%s(%q) в поясе %s: записано местное 29.07.2026 17:25:37", fn, c.хранимое, c.з.имя)
			}
		})
	}
}

// Дата без времени суток НЕ уезжает на день назад.
//
// Это ровно тот риск, который правка обязана исключить: поле «Дата» пользователь
// заполняет календарным днём, форма разбирает его как местную полночь
// (ui.canonicalFormDate → ParseInLocation в time.Local), и в UTC уезжает уже
// сама полночь. В отрицательном поясе хранимое значение приходится на СЛЕДУЮЩИЕ
// сутки по UTC, в положительном — на предыдущие; прочитанный день обязан
// остаться тем, который ввели.
func TestДатаИзЗапроса_КалендарныйДеньНеСдвигается(t *testing.T) {
	cases := []struct {
		з        зона
		хранимое string
	}{
		{пояса[0], "2026-02-20T00:00:00Z"},
		{пояса[1], "2026-02-19T21:00:00Z"},
		{пояса[2], "2026-02-20T05:00:00Z"},
		{пояса[3], "2026-02-19T18:15:00Z"},
		{пояса[4], "2026-02-19T10:00:00Z"},
	}
	for _, c := range cases {
		t.Run(c.з.имя, func(t *testing.T) {
			закрепитьПояс(t, c.з)
			assert.Equal(t, float64(20), частьДаты(t, "День", c.хранимое),
				"День(%q) в поясе %s: введено 20 февраля", c.хранимое, c.з.имя)
			assert.Equal(t, float64(2), частьДаты(t, "Месяц", c.хранимое))
			assert.Equal(t, float64(2026), частьДаты(t, "Год", c.хранимое))
			assert.Equal(t, float64(0), частьДаты(t, "Час", c.хранимое))
		})
	}
}

// Дата, хранимая БЕЗ зоны, — местные стенные часы (ParseRegPeriod читает такие
// раскладки через ParseInLocation). Приведение к локальному для них тождественно
// и день сдвинуть не может ни в каком поясе.
func TestДатаИзЗапроса_БезЗоныЭтоМестноеВремя(t *testing.T) {
	for _, з := range пояса {
		t.Run(з.имя, func(t *testing.T) {
			закрепитьПояс(t, з)
			for _, хранимое := range []string{
				"2026-02-20",
				"2026-02-20 17:25:37",
				"2026-02-20T17:25:37",
			} {
				assert.Equal(t, float64(20), частьДаты(t, "День", хранимое),
					"День(%q) в поясе %s", хранимое, з.имя)
				assert.Equal(t, float64(2026), частьДаты(t, "Год", хранимое))
			}
			// Время суток у раскладок с часами тоже местное, а не UTC.
			assert.Equal(t, float64(17), частьДаты(t, "Час", "2026-02-20 17:25:37"))
			assert.Equal(t, float64(17), частьДаты(t, "Час", "2026-02-20T17:25:37"))
		})
	}
}

// И PostgreSQL (time.Time), и SQLite (RFC3339-строка) обязаны приводить один
// момент к местной зоне до форматирования. На границе суток это проверяет не
// только вид строки, но и согласованность Формат с уже исправленным Днём.
func TestДатаИзЗапроса_ФорматСогласованСДнём(t *testing.T) {
	закрепитьПояс(t, зона{"MSK", 3 * 3600})
	for _, прочитано := range []any{
		time.Date(2026, 7, 29, 22, 25, 0, 0, time.UTC),
		"2026-07-29T22:25:00Z",
	} {
		assert.Equal(t, "30.07.2026", форматДаты(t, прочитано),
			"Формат над датой из запроса (%T)", прочитано)
		assert.Equal(t, float64(30), частьДаты(t, "День", прочитано),
			"Формат и День должны видеть один местный день")
	}
}

// Формат обязан принимать обе legacy-раскладки без зоны, которые умеет читать
// общий датный путь. Это местные стенные часы: смена часового пояса процесса не
// должна сдвигать выписанный в строке календарный день.
func TestДатаИзЗапроса_ФорматПринимаетLegacyСтроки(t *testing.T) {
	for _, з := range пояса {
		t.Run(з.имя, func(t *testing.T) {
			закрепитьПояс(t, з)
			for _, хранимое := range []string{
				"2026-07-29 22:25:00",
				"2026-07-29T22:25:00",
			} {
				assert.Equal(t, "29.07.2026", форматДаты(t, хранимое),
					"Формат(%q) в поясе %s", хранимое, з.имя)
			}
		})
	}
}

// Раскладка со ЯВНЫМ смещением задаёт инстант: он приводится к закреплённому
// поясу, а не читается как местные часы.
func TestДатаИзЗапроса_ЯвноеСмещениеЭтоИнстант(t *testing.T) {
	cases := []struct {
		з    зона
		час  float64
		день float64
	}{
		{пояса[1], 17, 29}, // MSK: +03:00 — тот же час
		{пояса[2], 9, 29},  // NY: 14:25Z → 09:25
		{пояса[4], 4, 30},  // LINT: 14:25Z → 04:25 СЛЕДУЮЩИХ суток
	}
	for _, c := range cases {
		t.Run(c.з.имя, func(t *testing.T) {
			закрепитьПояс(t, c.з)
			const хранимое = "2026-07-29T17:25:37+03:00"
			assert.Equal(t, c.час, частьДаты(t, "Час", хранимое),
				"Час(%q) в поясе %s", хранимое, c.з.имя)
			assert.Equal(t, c.день, частьДаты(t, "День", хранимое))
		})
	}
}

// PostgreSQL отдаёт дату из запроса уже как time.Time (в UTC), а не строкой —
// ветка, до которой SQLite-тесты не доходят. Стенные часы обязаны быть теми же,
// что и у строкового представления того же момента.
func TestДатаИзЗапроса_ЗначениеTimeTimeТожеМестное(t *testing.T) {
	for _, c := range []struct {
		з   зона
		час float64
	}{
		{пояса[0], 14},
		{пояса[1], 17},
		{пояса[2], 9},
	} {
		t.Run(c.з.имя, func(t *testing.T) {
			закрепитьПояс(t, c.з)
			момент := time.Date(2026, 7, 29, 14, 25, 37, 0, time.UTC)
			assert.Equal(t, c.час, частьДаты(t, "Час", момент),
				"Час(time.Time 14:25:37Z) в поясе %s", c.з.имя)
			assert.Equal(t, float64(29), частьДаты(t, "День", момент))
		})
	}
}

// Произвольная строка датой не становится: молчаливое приведение мусора к дате
// хуже, чем честное Неопределено — иначе Час("ЗАЯ-000001") дал бы 0 и отбор по
// часу тихо сработал бы не на тех записях.
func TestДатаИзЗапроса_НеДатаОстаётсяНеопределено(t *testing.T) {
	for _, s := range []string{"", "не дата", "ЗАЯ-000001", "2026-13-45"} {
		assert.Nil(t, частьДаты(t, "Час", s), "Час(%q)", s)
		assert.Nil(t, частьДаты(t, "День", s), "День(%q)", s)
	}
}

// НачалоДня над датой из запроса даёт местную полночь ТОГО ЖЕ дня. Соседние
// функции слоя (dateBegWeek, dateEndMonth) строят результат в time.Local, и без
// приведения в toTime день брался из UTC-часов, а полночь достраивалась
// локальная — два разных отсчёта в одном значении.
func TestДатаИзЗапроса_НачалоДняСогласованоСДнём(t *testing.T) {
	for _, c := range []struct {
		з        зона
		хранимое string
	}{
		{пояса[1], "2026-07-29T14:25:37Z"}, // местное 17:25
		{пояса[2], "2026-07-29T22:25:37Z"}, // местное 17:25
	} {
		t.Run(c.з.имя, func(t *testing.T) {
			закрепитьПояс(t, c.з)
			got := evalWithVars(t,
				"Функция Т()\n  Возврат НачалоДня(Прочитано);\nКонецФункции",
				map[string]any{"Прочитано": c.хранимое})
			начало, ok := got.(time.Time)
			if !ok {
				t.Fatalf("НачалоДня(%q) = %#v, ожидалась дата", c.хранимое, got)
			}
			assert.Equal(t, 29, начало.Day(), "день начала суток")
			assert.Equal(t, 0, начало.Hour(), "часы начала суток")
			assert.Equal(t, time.Local, начало.Location(), "зона начала суток")
		})
	}
}
