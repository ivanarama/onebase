package interpreter_test

// Пустая ссылка в параметре запроса. Раньше она уходила пустой строкой, и на
// PostgreSQL отбор «(&Все ИЛИ Номенклатура = &Ном)» с невыбранным полем падал
// («operator does not exist: uuid = text»), хотя на SQLite работал: условие с
// флагом СУБД всё равно проверяет на типы. Теперь на PostgreSQL пустая ссылка —
// NULL: отбор с флагом выключается, без флага не находит ничего, ошибки нет.
//
// Через публичную точку входа: модуль исполняется целиком поверх живой базы,
// пустая ссылка берётся из результата запроса — так она приходит в формах.

import (
	"context"
	"testing"

	"github.com/google/uuid"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/ivantit66/onebase/internal/dbtest"
	"github.com/ivantit66/onebase/internal/storage"
)

func TestQueryEmptyRefParamMatrix(t *testing.T) {
	dbtest.ForEachDialect(t, func(t *testing.T, db *storage.DB) {
		ents := refQueryEntities()
		seedRefQueryData(t, db, ents)
		// Второй документ — без номенклатуры: его колонка даёт пустую ссылку.
		require.NoError(t, db.Upsert(context.Background(), ents[1].Name, uuid.New(),
			map[string]any{"номер": "РТ-2"}, ents[1]))

		const src = `Процедура Тест()
			Запрос = Новый Запрос;
			Запрос.Текст = "ВЫБРАТЬ Номенклатура ИЗ Документ.РасходТовара ГДЕ Номер = ""РТ-2""";
			Пусто = Запрос.Выполнить()[0].Номенклатура;
			Отчёт = Строка(ЗначениеЗаполнено(Пусто));

			З = Новый Запрос;
			З.Текст = "ВЫБРАТЬ Номер ИЗ Документ.РасходТовара ГДЕ (&Все ИЛИ Номенклатура = &Ном) УПОРЯДОЧИТЬ ПО Номер";
			З.УстановитьПараметр("Все", Истина);
			З.УстановитьПараметр("Ном", Пусто);
			Н = 0;
			Для Каждого С Из З.Выполнить() Цикл
				Н = Н + 1;
			КонецЦикла;
			Отчёт = Отчёт + "|все:" + Строка(Н);

			З.УстановитьПараметр("Все", Ложь);
			Н = 0;
			Для Каждого С Из З.Выполнить() Цикл
				Н = Н + 1;
			КонецЦикла;
			Возврат Отчёт + "|отбор:" + Строка(Н);
		КонецПроцедуры`

		assert.Equal(t, "false|все:2|отбор:0", runOnDBEntities(t, db, ents, src))
	})
}
