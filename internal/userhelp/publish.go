package userhelp

import (
	"context"
	"crypto/sha256"
	"fmt"
	"html"
	"io"
	"net/url"
	"path"
	"sort"
	"strings"

	nethtml "golang.org/x/net/html"
)

// Publisher is independent of Confluence and of any particular MCP server.
// A publisher may implement this contract using REST or an agent's MCP tools.
type Publisher interface {
	ReadPage(context.Context, string) (RemotePage, error)
	CreatePage(context.Context, string, string) (RemotePage, error)
	UpdatePage(context.Context, RemotePage, string, string) (RemotePage, error)
	PutImage(context.Context, string, string, Asset) error
	PageURL(string) string
}

type RemotePage struct {
	ID      string `json:"id"`
	Version int    `json:"version"`
	Hash    string `json:"hash,omitempty"`
	Parent  string `json:"parent,omitempty"`
}

// PublishState belongs to a single target (base URL, space, root page). It has
// no credentials. A changed remote version is a conflict, never an overwrite.
type PublishState struct {
	Target string                `json:"target"`
	Pages  map[string]RemotePage `json:"pages"`
}

// Publish checkpoints after every remote mutation, so reruns reuse page IDs.
// It never deletes remote pages. Local removal leaves the old publication intact.
func (b *Book) Publish(ctx context.Context, p Publisher, root string, state *PublishState, checkpoint func() error) error {
	if !b.Available() {
		return fmt.Errorf("user documentation is disabled or empty")
	}
	if state.Pages == nil {
		state.Pages = map[string]RemotePage{}
	}
	// Validate existing pages before making any changes.
	for _, c := range b.Chapters {
		if saved, ok := state.Pages[c.ID]; ok {
			if saved.Parent != c.Parent {
				return fmt.Errorf("chapter %s: parent changed; reconcile the remote hierarchy and publication state first", c.ID)
			}
			remote, err := p.ReadPage(ctx, saved.ID)
			if err != nil {
				return fmt.Errorf("chapter %s: %w", c.ID, err)
			}
			if remote.Version != saved.Version {
				return fmt.Errorf("chapter %s: remote page changed (version %d, expected %d); reconcile edits before publishing", c.ID, remote.Version, saved.Version)
			}
		}
	}
	for _, c := range b.Chapters {
		if _, ok := state.Pages[c.ID]; ok {
			continue
		}
		parent := root
		if c.Parent != "" {
			parent = state.Pages[c.Parent].ID
		}
		remote, err := p.CreatePage(ctx, parent, c.Title)
		if err != nil {
			return fmt.Errorf("create chapter %s: %w", c.ID, err)
		}
		remote.Parent = c.Parent
		state.Pages[c.ID] = remote
		if err := checkpoint(); err != nil {
			return fmt.Errorf("checkpoint page %s (%s): %w", c.ID, remote.ID, err)
		}
	}
	for i := range b.Chapters {
		c := &b.Chapters[i]
		remote := state.Pages[c.ID]
		body, err := b.Render(c, func(id string) string { return p.PageURL(state.Pages[id].ID) }, func(asset string) string {
			return "onebase-image/" + attachmentName(asset, b.Assets[asset])
		})
		if err != nil {
			return err
		}
		// Convert only the image tags generated by our Markdown renderer.
		body, names, err := confluenceImages(body)
		if err != nil {
			return err
		}
		digest := fmt.Sprintf("%x", sha256.Sum256([]byte(c.Title+"\n"+c.Parent+"\n"+body)))
		for _, assetPath := range b.assetPaths() {
			a := b.Assets[assetPath]
			name := attachmentName(assetPath, a)
			if names[name] {
				if err := p.PutImage(ctx, remote.ID, name, a); err != nil {
					return fmt.Errorf("upload %s: %w", assetPath, err)
				}
			}
		}
		if remote.Hash == digest {
			continue
		}
		updated, err := p.UpdatePage(ctx, remote, c.Title, body)
		if err != nil {
			return fmt.Errorf("update chapter %s: %w", c.ID, err)
		}
		updated.Hash = digest
		updated.Parent = c.Parent
		state.Pages[c.ID] = updated
		if err := checkpoint(); err != nil {
			return err
		}
	}
	return nil
}

func attachmentName(p string, a Asset) string {
	return fmt.Sprintf("onebase-%x%s", sha256.Sum256(a.Data), strings.ToLower(path.Ext(p)))
}

func (b *Book) assetPaths() []string {
	paths := make([]string, 0, len(b.Assets))
	for p := range b.Assets {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	return paths
}

func escapedPageURL(base, id string) string {
	return strings.TrimRight(base, "/") + "/pages/viewpage.action?pageId=" + url.QueryEscape(id)
}

// confluenceImages changes generated <img> nodes to Confluence storage markup.
func confluenceImages(body string) (string, map[string]bool, error) {
	names := map[string]bool{}
	var out strings.Builder
	z := nethtml.NewTokenizer(strings.NewReader(body))
	for {
		tt := z.Next()
		if tt == nethtml.ErrorToken {
			if err := z.Err(); err != nil && err != io.EOF {
				return "", nil, err
			}
			break
		}
		raw := string(z.Raw())
		if tt == nethtml.StartTagToken || tt == nethtml.SelfClosingTagToken {
			tok := z.Token()
			if tok.Data == "img" {
				for _, a := range tok.Attr {
					if a.Key == "src" && strings.HasPrefix(a.Val, "onebase-image/") {
						name := strings.TrimPrefix(a.Val, "onebase-image/")
						names[name] = true
						fmt.Fprintf(&out, `<ac:image><ri:attachment ri:filename="%s" /></ac:image>`, html.EscapeString(name))
					}
				}
				continue
			}
		}
		out.WriteString(raw)
	}
	return out.String(), names, nil
}
