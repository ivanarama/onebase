package launcher

import (
	"io"
	"os"
)

// Уборка и завершение — ошибки, которые не меняют исход операции.
//
// План 109 запрещает механически превращать такие места в `_ =`, и правильно:
// без пояснения непонятно, решение это или недосмотр. Но и возвращать их
// вызывающему нельзя — к моменту уборки основная работа либо уже сделана, либо
// уже провалилась со своей ошибкой, и подмена причины вторичной теряет
// настоящую.
//
// Поэтому решение принято здесь один раз: ошибка уходит в журнал на Debug с
// указанием, что именно не убралось. Debug, а не Warn, потому что эти сбои —
// штатный фон: занятый файл на Windows, гонка с антивирусом, уже закрытое
// соединение. На Warn журнал конфигуратора превратился бы в шум, и настоящие
// предупреждения в нём потерялись бы.
//
// Границы, за которые эти помощники брать нельзя:
//   - Close ПИШУЩЕЙ стороны: там Close сбрасывает буфер, и его ошибка основная
//     (см. tempfile.go и archive.go);
//   - остановка базы перед восстановлением: там сбой меняет исход операции.

// bestEffort фиксирует ошибку уборки, не меняя исход операции.
// what — что именно не удалось, в форме «удалить временный каталог».
func bestEffort(what string, err error) {
	if err != nil {
		respondLog().Debug("не удалось "+what, "err", err)
	}
}

// removeTemp удаляет временный файл или каталог.
func removeTemp(path string) {
	if err := os.RemoveAll(path); err != nil {
		respondLog().Debug("не удалось удалить временный путь", "path", path, "err", err)
	}
}

// closeRead закрывает читающую сторону (загруженный файл, тело ответа, открытый
// исходник). Данные к этому моменту уже прочитаны.
func closeRead(what string, c io.Closer) {
	if err := c.Close(); err != nil {
		respondLog().Debug("не удалось закрыть "+what, "err", err)
	}
}

// copyProxied переливает тело ответа базы в уже начатый ответ конфигуратора.
// Заголовки и статус отправлены, поменять их нельзя — как и в respond.go,
// остаётся зафиксировать обрыв и прекратить запись.
func copyProxied(w io.Writer, body io.Reader) {
	if _, err := io.Copy(w, body); err != nil {
		respondLog().Debug("проксируемый ответ базы не дописан", "err", err)
	}
}
