package launcher

import "fmt"

// cfgTypeSets — значения, которые предлагает выпадающий список типа в каждом
// редакторе конфигуратора. Ключ — набор, переданный шаблоном.
//
// Списки продублированы с разметкой намеренно: подписи пунктов обязаны
// остаться вызовами функции перевода прямо в шаблоне, потому что ключи
// собирает tools/i18ncheck регуляркой по разметке, и перенос подписей в
// Go-код вывел бы их из-под гейта переводов. Расхождение двух списков сторожит
// TestCfgTypeSets_MatchTemplateOptions: он вычитывает <option value> прямо из
// отрисованной страницы и сверяет с этой картой.
var cfgTypeSets = map[string][]string{
	// Реквизиты справочника/документа и полей табличной части.
	"entity": {"string", "number", "date", "bool", "reference", "enum", "image", "richtext"},
	// Измерения, ресурсы и реквизиты регистров накопления и сведений.
	// Перечисления регистр хранить умеет, но выбрать их в списке нельзя:
	// соседний список объектов перечислений не показывает. Существующие
	// поля enum: набор не предлагает — их сохраняет запасной пункт.
	"register": {"string", "number", "date", "bool", "reference"},
	// Ресурсы плана счетов.
	"account": {"number", "string", "bool"},
	// Константы. Значение "boolean" — историческое: метаданные пишут "bool",
	// поэтому булева константа в набор не попадает и живёт запасным пунктом.
	"constant": {"string", "number", "date", "boolean", "reference"},

	// Наборы для НОВОЙ строки: её список рисует cfgAddField в
	// static/configurator.js, а не шаблон.
	//
	// «entity-new» совпадает с «entity» — реквизит-картинку теперь можно и
	// завести, а не только сохранить существующий.
	//
	// «register-new» ШИРЕ, чем «register», и это не опечатка: измерение-
	// перечисление через «+ Добавить» завести можно (cfgToggleRef подставляет
	// список перечислений), а в отрисованной строке существующего измерения
	// пункта «перечисление» нет — поэтому сменить перечисление у уже
	// заведённого измерения нельзя. Асимметрия досталась в наследство. Порчи
	// она больше не даёт: запасной пункт сохраняет такой тип при любой правке
	// регистра. Набор зафиксирован здесь, чтобы расхождение осталось
	// осознанным и не расползлось дальше молча.
	"entity-new":   {"string", "number", "date", "bool", "reference", "enum", "image", "richtext"},
	"register-new": {"string", "number", "date", "bool", "reference", "enum"},
}

// cfgUnlistedType возвращает тип, если выпадающий список набора set его НЕ
// предлагает, и пустую строку, если предлагает. Шаблон по непустому ответу
// дорисовывает пункт с настоящим типом и помечает его selected.
//
// Зачем это нужно. <select>, ни один пункт которого не помечен selected,
// браузер отправляет ПЕРВЫМ пунктом списка. Поле с типом вне набора — image и
// richtext у реквизита, enum: у измерения регистра, bool у константы — уезжало
// на сервер «строкой», а сохранение переписывало YAML присланным значением, не
// сверяясь с прежним. Поэтому правка ЛЮБОГО реквизита молча меняла тип
// соседнего поля: добавление реквизита в Номенклатуру превращало «Фото» из
// картинки в строку, после чего конфигурация переставала загружаться —
// «tile_view.image field Фото must have type image» (#1090).
//
// Чинить это добавлением недостающих пунктов недостаточно: список отстанет от
// метаданных при следующем новом типе, причём молча и с порчей данных. Пункт с
// текущим значением делает отставание безвредным — список всегда содержит то,
// что в файле.
func cfgUnlistedType(set, typ string) string {
	if typ == "" {
		return ""
	}
	for _, known := range cfgTypeSets[set] {
		if known == typ {
			return ""
		}
	}
	return typ
}

// cfgUnlistedFieldType — то же для поля объекта или регистра. Возвращает тип в
// полной записи метаданных: у ссылки и перечисления вид списка хранит короткое
// «reference»/«enum», а объект лежит в соседнем списке, и запасной пункт обязан
// нести значение целиком («enum:РезультатСделки»), иначе разбор формы получит
// «enum» без имени перечисления и запишет заведомо нерабочий тип.
func cfgUnlistedFieldType(set string, f cfgField) string {
	if cfgUnlistedType(set, f.Type) == "" {
		return ""
	}
	switch {
	case f.RefEntity != "":
		return "reference:" + f.RefEntity
	case f.EnumName != "":
		return "enum:" + f.EnumName
	case f.Type == "number" && f.Length > 0:
		return fmt.Sprintf("number(%d,%d)", f.Length, f.Scale)
	}
	return f.Type
}
