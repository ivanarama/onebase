package launcher

import (
	"encoding/json"
	"html/template"
	"log/slog"
	"net/http"

	oblog "github.com/ivantit66/onebase/internal/logging"
)

// Запись в уже начатый HTTP-ответ.
//
// К моменту этих вызовов заголовки отправлены (а часто и часть тела), поэтому
// вернуть пользователю другой статус нельзя — план 109 предписывает для такого
// случая зафиксировать сбой структурным логом и прекратить запись. Решение
// принято здесь один раз, вместо того чтобы повторяться в каждом обработчике.
//
// Уровень выбирается не по размеру ответа, а по одному признаку: **заметит ли
// пользователь обрыв**.
//
//   - Страница, HTML-фрагмент админки, JSON для фонового запроса — обрыв виден
//     сразу: браузер рисует пустоту, JS падает на разборе. Причина почти всегда
//     внешняя (закрыли вкладку, ушла сеть), чинить в коде нечего → Debug.
//     Warn здесь залил бы журнал при каждом закрытии вкладки конфигуратора.
//   - Файл, который пользователь сохраняет или правит (экспорт .zip/.obz,
//     исходник из дерева файлов), — обрыв НЕ виден: получается усечённый файл,
//     внешне неотличимый от целого. Такой архив ляжет в резервные копии и
//     всплывёт только при восстановлении, а усечённый исходник вернётся в
//     конфигурацию при следующем сохранении из редактора → Warn.
//   - Сбой шаблона чаще означает ошибку в самом шаблоне (нет поля, nil-карта),
//     а не разрыв соединения, и страница приходит обрезанной → Warn.

func respondLog() *slog.Logger { return oblog.Component("launcher") }

// writeBody дописывает тело уже начатого ответа: страницу, HTML-фрагмент,
// превью. Для содержимого, которое пользователь сохранит на диск, есть
// writeDownload — там обрыв надо видеть.
//
// G705 (taint-анализ gosec) видит здесь единый сток для всех HTML-ответов
// лаунчера и не видит санитизацию, потому что она сделана не стандартными
// html.EscapeString/template: предпросмотр макета (единственный путь, из-за
// которого правило срабатывает, — проверено побайтовым отключением вызовов)
// экранируется внутри internal/sheet — escapeHTML для текста ячейки,
// richtext.Sanitize для Cell.RichHTML, csssafe для цвета и шрифта, allowlist
// classifyPicture для src картинки. Остальные вызывающие подставляют данные
// через html.EscapeString/escHTML.
func writeBody(w http.ResponseWriter, b []byte) {
	if _, err := w.Write(b); err != nil { //nolint:gosec // G705: HTML санитизируется в internal/sheet и escHTML — gosec эти санитайзеры не распознаёт
		respondLog().Debug("не удалось записать тело ответа", "err", err)
	}
}

// writeDownload отдаёт содержимое, которое пользователь сохраняет как файл или
// правит в редакторе. Обрыв здесь даёт внешне целый, но усечённый файл, поэтому
// он попадает в журнал как предупреждение с именем ресурса.
//
// Содержимое здесь по определению не HTML-страница: архивы уходят с
// Content-Disposition: attachment, а просмотр исходника из дерева файлов (путь,
// из-за которого срабатывает G705) — с text/plain и X-Content-Type-Options:
// nosniff, то есть браузер его не исполняет. Заголовки ставит вызывающий, и
// taint-анализ их не учитывает; guard закреплён тестом
// TestConfiguratorFileRawServesInertContentType.
func writeDownload(w http.ResponseWriter, name string, b []byte) {
	if _, err := w.Write(b); err != nil { //nolint:gosec // G705: ответ не является HTML-страницей — attachment либо text/plain + nosniff
		respondLog().Warn("ответ с файлом оборван — содержимое у пользователя усечено",
			"file", name, "size", len(b), "err", err)
	}
}

// respondJSONTo кодирует значение прямо в ответ.
func respondJSONTo(w http.ResponseWriter, v any) {
	if err := json.NewEncoder(w).Encode(v); err != nil {
		respondLog().Debug("не удалось записать JSON-ответ", "err", err)
	}
}

// renderTemplate отрисовывает шаблон в уже начатый ответ.
func renderTemplate(w http.ResponseWriter, t *template.Template, data any) {
	if err := t.Execute(w, data); err != nil {
		respondLog().Warn("не удалось отрисовать шаблон", "template", t.Name(), "err", err)
	}
}
