package launcher

import (
	"html"
	"net/http"
)

// httpErrorDiv отвечает фрагментом с сообщением об ошибке — тем же оформлением,
// что уже используется в обработчиках лаунчера («Нет подключения к БД» и т. п.).
//
// Нужен, чтобы отказ был виден. Раньше сбой подготовки схемы игнорировался, а
// следом игнорировалась и ошибка чтения — администратор видел пустой список и
// делал вывод, что пользователей (ролей, сессий) просто нет.
//
// Текст ошибки экранируется: он приходит из БД и может содержать имена объектов
// с угловыми скобками или кавычками, которые иначе поехали бы в разметку.
func httpErrorDiv(w http.ResponseWriter, msg string, err error) {
	body := `<div style="padding:16px;color:#c00">` + html.EscapeString(msg)
	if err != nil {
		body += ": " + html.EscapeString(err.Error())
	}
	body += `</div>`
	// Ошибка записи в ответ означает, что клиент отсоединился: обрабатывать
	// нечем и незачем — сам канал ответа и сломан.
	_, _ = w.Write([]byte(body))
}
